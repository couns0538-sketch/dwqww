// Texel-style evaluation tuner.
//
// Reads positions produced by forge_extract ("<fen> <result> <score>"), builds
// the linear coefficient trace of every position once, then fits all evaluation
// parameters with Adam on the mean squared error between the sigmoid of the
// evaluation and a blend of game result and search score.
//
// Usage:
//   forge_texel positions.txt [--epochs N] [--lr X] [--lambda L] [--threads T]
//               [--min-count C] [--decay-every D] [--reg R] [--rarity F] [--first-index I]
//               [--out table.inc]
//   forge_texel --dump table.inc      (write the current parameters)
//
// --first-index I keeps parameters 0..I-1 at their current values and fits
// only the parameters from index I on (used to fit newly added terms).
#include "forge/board.hpp"
#include "forge/eval_params.hpp"

#include <algorithm>
#include <atomic>
#include <chrono>
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <iostream>
#include <mutex>
#include <sstream>
#include <string>
#include <thread>
#include <vector>

namespace {

struct Sample {
    std::uint32_t offset = 0;
    std::uint16_t count = 0;
    std::uint8_t phase = 0;
    std::uint8_t scale = 64;
    float result = 0.5F;
    float score = 0.0F;
    bool has_score = false;
};

struct Term {
    std::int16_t index;
    std::int16_t coefficient;
};

double sigmoid(double x, double k) { return 1.0 / (1.0 + std::exp(-k * x / 400.0)); }

void write_table(const std::string& path, const std::vector<double>& mg, const std::vector<double>& eg) {
    std::ofstream out(path);
    out << "// Generated by forge_texel. One entry per forge::params::Index.\n";
    for (int i = 0; i < forge::params::Count; ++i) {
        out << "/* " << i << ' ' << forge::params::name(i) << " */ S("
            << static_cast<int>(std::lround(mg[static_cast<std::size_t>(i)])) << ", "
            << static_cast<int>(std::lround(eg[static_cast<std::size_t>(i)])) << "),\n";
    }
    std::cerr << "wrote " << path << '\n';
}

} // namespace

int main(int argc, char** argv) {
    std::string input_path;
    std::string output_path = "eval_params_table.inc";
    std::string dump_path;
    int epochs = 400;
    double learning_rate = 1.0;
    double lambda = 0.5;
    int threads = static_cast<int>(std::max(1U, std::thread::hardware_concurrency()));
    int min_count = 40;
    int decay_every = 150;
    double regularization = 1e-8;
    double rarity_fraction = 0.005;
    int first_index = 0;
    for (int i = 1; i < argc; ++i) {
        const std::string arg = argv[i];
        auto next = [&]() -> std::string { return i + 1 < argc ? argv[++i] : ""; };
        if (arg == "--epochs") epochs = std::stoi(next());
        else if (arg == "--lr") learning_rate = std::stod(next());
        else if (arg == "--lambda") lambda = std::stod(next());
        else if (arg == "--threads") threads = std::stoi(next());
        else if (arg == "--min-count") min_count = std::stoi(next());
        else if (arg == "--decay-every") decay_every = std::stoi(next());
        else if (arg == "--reg") regularization = std::stod(next());
        else if (arg == "--rarity") rarity_fraction = std::stod(next());
        else if (arg == "--first-index") first_index = std::stoi(next());
        else if (arg == "--out") output_path = next();
        else if (arg == "--dump") dump_path = next();
        else input_path = arg;
    }

    std::vector<double> mg(forge::params::Count);
    std::vector<double> eg(forge::params::Count);
    for (int i = 0; i < forge::params::Count; ++i) {
        mg[static_cast<std::size_t>(i)] = forge::mg_value(forge::params::table[static_cast<std::size_t>(i)]);
        eg[static_cast<std::size_t>(i)] = forge::eg_value(forge::params::table[static_cast<std::size_t>(i)]);
    }
    const std::vector<double> initial_mg = mg;
    const std::vector<double> initial_eg = eg;
    if (!dump_path.empty()) {
        write_table(dump_path, mg, eg);
        return 0;
    }
    if (input_path.empty()) {
        std::cerr << "usage: forge_texel positions.txt [options]\n";
        return 2;
    }

    // Load and trace every position.
    std::vector<Sample> samples;
    std::vector<Term> terms;
    std::vector<std::uint32_t> usage(forge::params::Count, 0);
    {
        std::ifstream input(input_path);
        if (!input) {
            std::cerr << "cannot open " << input_path << '\n';
            return 1;
        }
        std::string line;
        forge::Board board;
        forge::EvalTrace trace;
        std::uint64_t mismatches = 0;
        while (std::getline(input, line)) {
            std::istringstream fields(line);
            std::string placement, side, castling, ep, half, full, result_text, score_text;
            if (!(fields >> placement >> side >> castling >> ep >> half >> full >> result_text)) continue;
            fields >> score_text;
            const std::string fen = placement + ' ' + side + ' ' + castling + ' ' + ep + ' ' + half + ' ' + full;
            if (!board.set_fen(fen) || board.in_check()) continue;
            const int white_eval = forge::evaluate_traced(board, trace);
            Sample sample;
            sample.offset = static_cast<std::uint32_t>(terms.size());
            sample.phase = static_cast<std::uint8_t>(trace.phase);
            sample.scale = static_cast<std::uint8_t>(trace.scale);
            sample.result = std::stof(result_text);
            if (!score_text.empty() && score_text != "none") {
                sample.score = std::stof(score_text);
                sample.has_score = true;
            }
            double reconstructed_mg = 0.0;
            double reconstructed_eg = 0.0;
            for (int i = 0; i < forge::params::Count; ++i) {
                const int coefficient = trace.coefficients[static_cast<std::size_t>(i)];
                if (coefficient == 0) continue;
                terms.push_back(Term{static_cast<std::int16_t>(i), static_cast<std::int16_t>(coefficient)});
                ++usage[static_cast<std::size_t>(i)];
                reconstructed_mg += coefficient * mg[static_cast<std::size_t>(i)];
                reconstructed_eg += coefficient * eg[static_cast<std::size_t>(i)];
            }
            sample.count = static_cast<std::uint16_t>(terms.size() - sample.offset);
            const int scaled_eg = static_cast<int>(reconstructed_eg) * trace.scale / 64;
            const int reconstructed = (static_cast<int>(reconstructed_mg) * trace.phase + scaled_eg * (forge::MaxPhase - trace.phase)) / forge::MaxPhase;
            if (std::abs(reconstructed - white_eval) > 2) ++mismatches;
            samples.push_back(sample);
        }
        std::cerr << "loaded " << samples.size() << " positions, " << terms.size() << " terms, "
                  << mismatches << " trace mismatches\n";
        if (samples.empty()) return 1;
    }

    auto evaluate_sample = [&](const Sample& s) {
        double total_mg = 0.0;
        double total_eg = 0.0;
        for (std::uint32_t t = s.offset; t < s.offset + s.count; ++t) {
            total_mg += terms[t].coefficient * mg[static_cast<std::size_t>(terms[t].index)];
            total_eg += terms[t].coefficient * eg[static_cast<std::size_t>(terms[t].index)];
        }
        return (total_mg * s.phase + total_eg * s.scale / 64.0 * (forge::MaxPhase - s.phase)) / forge::MaxPhase;
    };

    // Fit the sigmoid scale K to the game results with the current parameters.
    double best_k = 1.0;
    {
        double best_error = 1e9;
        for (double k = 0.3; k <= 4.0; k += 0.05) {
            double error = 0.0;
            for (const Sample& s : samples) {
                const double diff = sigmoid(evaluate_sample(s), k) - s.result;
                error += diff * diff;
            }
            error /= static_cast<double>(samples.size());
            if (error < best_error) {
                best_error = error;
                best_k = k;
            }
        }
        std::cerr << "K = " << best_k << " initial result-MSE = " << best_error << '\n';
    }

    // Adam optimiser state.
    const std::size_t n = static_cast<std::size_t>(forge::params::Count);
    std::vector<double> m_mg(n), v_mg(n), m_eg(n), v_eg(n);
    const double beta1 = 0.9;
    const double beta2 = 0.999;
    const double epsilon = 1e-8;
    std::vector<std::vector<double>> grad_mg(static_cast<std::size_t>(threads), std::vector<double>(n));
    std::vector<std::vector<double>> grad_eg(static_cast<std::size_t>(threads), std::vector<double>(n));
    std::vector<double> losses(static_cast<std::size_t>(threads));

    const auto start = std::chrono::steady_clock::now();
    for (int epoch = 1; epoch <= epochs; ++epoch) {
        std::vector<std::thread> workers;
        for (int t = 0; t < threads; ++t) {
            workers.emplace_back([&, t]() {
                auto& gm = grad_mg[static_cast<std::size_t>(t)];
                auto& ge = grad_eg[static_cast<std::size_t>(t)];
                std::fill(gm.begin(), gm.end(), 0.0);
                std::fill(ge.begin(), ge.end(), 0.0);
                double loss = 0.0;
                const std::size_t begin = samples.size() * static_cast<std::size_t>(t) / static_cast<std::size_t>(threads);
                const std::size_t end = samples.size() * static_cast<std::size_t>(t + 1) / static_cast<std::size_t>(threads);
                for (std::size_t i = begin; i < end; ++i) {
                    const Sample& s = samples[i];
                    const double eval = evaluate_sample(s);
                    const double prediction = sigmoid(eval, best_k);
                    double target = s.result;
                    if (s.has_score) target = lambda * s.result + (1.0 - lambda) * sigmoid(s.score, best_k);
                    const double diff = prediction - target;
                    loss += diff * diff;
                    const double d_eval = 2.0 * diff * prediction * (1.0 - prediction) * best_k / 400.0;
                    const double d_mg = d_eval * s.phase / forge::MaxPhase;
                    const double d_eg = d_eval * (forge::MaxPhase - s.phase) * s.scale / (64.0 * forge::MaxPhase);
                    for (std::uint32_t k = s.offset; k < s.offset + s.count; ++k) {
                        gm[static_cast<std::size_t>(terms[k].index)] += terms[k].coefficient * d_mg;
                        ge[static_cast<std::size_t>(terms[k].index)] += terms[k].coefficient * d_eg;
                    }
                }
                losses[static_cast<std::size_t>(t)] = loss;
            });
        }
        for (auto& worker : workers) worker.join();

        double loss = 0.0;
        for (const double l : losses) loss += l;
        loss /= static_cast<double>(samples.size());
        const double scale = 1.0 / static_cast<double>(samples.size());
        for (std::size_t i = static_cast<std::size_t>(std::max(0, first_index)); i < n; ++i) {
            if (usage[i] < static_cast<std::uint32_t>(min_count)) continue;
            double g_mg = 0.0;
            double g_eg = 0.0;
            for (int t = 0; t < threads; ++t) {
                g_mg += grad_mg[static_cast<std::size_t>(t)][i];
                g_eg += grad_eg[static_cast<std::size_t>(t)][i];
            }
            // Pull towards the initial values; this mostly anchors parameters
            // that the data rarely exercises, since Adam normalises step sizes.
            g_mg = g_mg * scale + regularization * (mg[i] - initial_mg[i]);
            g_eg = g_eg * scale + regularization * (eg[i] - initial_eg[i]);
            m_mg[i] = beta1 * m_mg[i] + (1.0 - beta1) * g_mg;
            v_mg[i] = beta2 * v_mg[i] + (1.0 - beta2) * g_mg * g_mg;
            m_eg[i] = beta1 * m_eg[i] + (1.0 - beta1) * g_eg;
            v_eg[i] = beta2 * v_eg[i] + (1.0 - beta2) * g_eg * g_eg;
            const double correction1 = 1.0 - std::pow(beta1, epoch);
            const double correction2 = 1.0 - std::pow(beta2, epoch);
            // Rare parameters take proportionally smaller steps so that a
            // handful of positions cannot drag them far from their defaults.
            const double rarity = std::min(1.0, static_cast<double>(usage[i]) / (rarity_fraction * static_cast<double>(samples.size())));
            const double step = learning_rate * rarity;
            mg[i] -= step * (m_mg[i] / correction1) / (std::sqrt(v_mg[i] / correction2) + epsilon);
            eg[i] -= step * (m_eg[i] / correction1) / (std::sqrt(v_eg[i] / correction2) + epsilon);
        }
        if (epoch % 10 == 0 || epoch == 1 || epoch == epochs) {
            const auto elapsed = std::chrono::duration_cast<std::chrono::seconds>(std::chrono::steady_clock::now() - start).count();
            std::cerr << "epoch " << epoch << " loss " << loss << " (" << elapsed << "s)\n";
        }
        if (epoch % 100 == 0) write_table(output_path, mg, eg);
        if (decay_every > 0 && epoch % decay_every == 0) learning_rate *= 0.5;
    }
    write_table(output_path, mg, eg);
    return 0;
}
