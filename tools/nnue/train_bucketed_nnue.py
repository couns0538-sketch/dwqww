"""Forge-768 residual SCReLU trainer with eight piece-count output heads.

Only the selected output head contributes to each row. Real training requires
an authenticated whole-game prepared corpus and a separate eight-head protocol;
the final-audit-only partition can never enter this optimizer. This utility does
not run an audit or establish playing strength.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path

import numpy as np
import torch
from torch import nn

from include_parser import load_include
from train_nnue import NNUE, SCALE, atomic_write, cpu_copy, feature_indices

HIDDEN, BUCKETS, K, CP_SCALE = 128, 8, 2.25, 400.0
COMBINED_CP_LIMIT = 31871


def sha256(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1 << 20), b''): digest.update(block)
    return digest.hexdigest()


def bucket_indices(features):
    """Map valid binary perspectives to clamp((pieces-1)//4,0,7)."""
    if features.ndim != 3 or tuple(features.shape[1:]) != (2, 768):
        raise ValueError('Expected binary features [N,2,768]')
    if not torch.isfinite(features).all() or not ((features == 0) | (features == 1)).all():
        raise ValueError('Piece-square features must be finite binary values')
    counts = features.sum(dim=2)
    if not torch.equal(counts[:, 0], counts[:, 1]) or not ((counts >= 2) & (counts <= 32)).all():
        raise ValueError('Both perspectives must describe the same 2..32 pieces, including kings')
    return ((counts[:, 0].to(torch.int64) - 1) // 4).clamp(0, 7)


class BucketedNNUE(nn.Module):
    """Shared 768->128 transform, two SCReLU perspectives, selected 256->1 head."""
    linear = NNUE.linear
    project_weights = NNUE.project_weights

    def __init__(self, qat=True):
        super().__init__()
        self.qat, self.shape = qat, [HIDDEN]
        self.ft = nn.Linear(768, HIDDEN)
        self.output = nn.Linear(2 * HIDDEN, BUCKETS)
        nn.init.normal_(self.ft.weight, std=0.02)
        nn.init.zeros_(self.ft.bias)
        nn.init.zeros_(self.output.bias)

    def forward(self, features):
        buckets = bucket_indices(features)
        accumulator = torch.clamp(self.linear(features, self.ft), 0.0, 1.0).square()
        logits = self.linear(accumulator.reshape(-1, 2 * HIDDEN), self.output)
        return logits.gather(1, buckets[:, None])


@torch.no_grad()
def load_initial(model, path):
    """Load a residual legacy head (replicated) or this exact eight-head format."""
    values = load_include(path, expected_hidden=HIDDEN)
    if not values['residual']:
        raise ValueError('Bucketed residual training requires a residual initial network')
    count = values['output_buckets']
    w2, b2 = values['bucket_w2'], values['bucket_b2']
    if count == 1:
        w2, b2 = np.repeat(w2, BUCKETS, axis=0), np.repeat(b2, BUCKETS)
    elif count != BUCKETS:
        raise ValueError('Initial output count must be 1 or 8')
    model.ft.weight.copy_(torch.from_numpy(values['w1'].T.copy()))
    model.ft.bias.copy_(torch.from_numpy(values['b1'].copy()))
    model.output.weight.copy_(torch.from_numpy(w2.copy()))
    model.output.bias.copy_(torch.from_numpy(b2.copy()))
    return {'path': str(Path(path).resolve()), 'sha256': values['sha256'],
            'source_output_buckets': count, 'output_buckets': BUCKETS, 'residual': True}


def export_bucketed(model, stem, sigmoid_k=K, residual=True):
    """Write bucket-major int16 include and versioned-by-metadata float32 arrays."""
    if sigmoid_k != K or residual is not True:
        raise ValueError('Eight-output export requires fixed2.25 residual mode')
    stem = Path(stem)
    paths = [stem.with_suffix(suffix) for suffix in ('.inc', '.bin', '.json')]
    if any(p.exists() for p in paths):
        raise FileExistsError('Export target already exists')
    arrays = [model.ft.weight.detach().cpu().T.contiguous().numpy().ravel(),
              model.ft.bias.detach().cpu().numpy(),
              model.output.weight.detach().cpu().contiguous().numpy().ravel(),
              model.output.bias.detach().cpu().numpy()]
    if [a.size for a in arrays] != [768 * HIDDEN, HIDDEN, BUCKETS * 2 * HIDDEN, BUCKETS]:
        raise ValueError('Eight-output model dimensions differ')
    quantized = []
    for array in arrays:
        if not np.isfinite(array).all(): raise ValueError('Cannot export nonfinite parameters')
        scaled = array.astype(np.float64) * SCALE
        rounded = np.sign(scaled) * np.floor(np.abs(scaled) + 0.5)
        if (np.abs(rounded) > 32767).any(): raise ValueError('Parameters exceed int16 range')
        quantized.append(rounded.astype(np.int16))
    lines = ['// Generated by train_bucketed_nnue.py; Forge residual eight-output network.',
             '#include <cstdint>', '#define FORGE_NNUE_RESIDUAL 1', '#define FORGE_NNUE_OUTPUT_BUCKETS 8',
             'static_assert(forge::nnue::InputCount == 768 && forge::nnue::HiddenSize == 128, "NNUE shape mismatch");',
             'static_assert(forge::nnue::SigmoidK == 2.25F, "NNUE output scale mismatch");',
             'static_assert(forge::nnue::WeightScale == 4096.0F && forge::nnue::OutputScale == 4096.0F, "NNUE quantization scale mismatch");']
    for name, array in zip(('NnueW1', 'NnueB1', 'NnueW2', 'NnueB2'), quantized):
        lines.append(f'static const std::int16_t {name}[{len(array)}] = {{')
        lines.extend('  ' + ', '.join(map(str, array[i:i+24])) + ',' for i in range(0, len(array), 24))
        lines.append('};')
    raw = b''.join(np.asarray(a, dtype='<f4').tobytes() for a in arrays)
    atomic_write(paths[0], lambda stream: stream.write(('\n'.join(lines)+'\n').encode('ascii')))
    atomic_write(paths[1], lambda stream: stream.write(raw))
    metadata = {'format': 'forge_residual_buckets8_v1', 'inputs': 768, 'accumulator': HIDDEN,
                'perspectives': 2, 'output_inputs': 2 * HIDDEN, 'output_buckets': BUCKETS,
                'bucket_rule': 'clamp((total_piece_count_including_kings-1)//4,0,7)',
                'activation': 'clamp(x,0,1)^2', 'weight_scale': SCALE, 'output_scale': SCALE,
                'cp_per_logit': CP_SCALE / K, 'residual': True, 'runtime_loader': False,
                'raw_float32_schema': 'feature_major_w1,b1,bucket_major_w2,bucket_b2',
                'raw_float32_bytes': len(raw), 'legacy_raw_loader_compatible': False,
                'inc_sha256': sha256(paths[0]), 'bin_sha256': sha256(paths[1])}
    atomic_write(paths[2], lambda stream: stream.write((json.dumps(metadata, indent=2)+'\n').encode()))
    return metadata


def validate_training_manifest(manifest):
    if (manifest.get('schema_version') != 1 or manifest.get('hidden_size') != HIDDEN
            or manifest.get('score_pov') != 'side_to_move' or manifest.get('result_pov') != 'side_to_move'
            or manifest.get('dataset_role') != 'training_and_selection'
            or manifest.get('training_permitted') is not True or manifest.get('status') != 'QUALIFIED_FROZEN'):
        raise ValueError('Only qualified training-and-selection whole-game data may optimize')
    minimum, total = manifest.get('minimum_positions'), manifest.get('retained_total_positions')
    if type(minimum) is not int or type(total) is not int or not 5000000 <= minimum <= total:
        raise ValueError('Independent-teacher corpus must retain at least5M positions')
    split = manifest.get('split', {})
    sets = []
    for name in ('train_game_ids', 'validation_game_ids'):
        games = split.get(name)
        if (not isinstance(games, list) or not games or any(not isinstance(g,str) or not g for g in games)
                or len(games) != len(set(games))): raise ValueError('Missing unique whole-game identities')
        sets.append(set(games))
    if sets[0] & sets[1] or split.get('legacy_training_game_ids_unknown') is not False:
        raise ValueError('Whole-game partitions overlap or contain unidentified games')


def validate_training_protocol(protocol, args):
    """Every effective optimizer/selection setting is fixed before reading a model."""
    target={'kind':'teacher_probability_game_result_blend','result_weight':args.result_weight,'sigmoid_k':K,'cp_scale':CP_SCALE}
    if not isinstance(protocol,dict): raise ValueError('Protocol must be a JSON object')
    policy=protocol.get('training')
    expected={'output_buckets':8,'epochs':args.epochs,'selection_metric':'target_mse_combined',
              'include_initial':False,'seed':args.seed,'batch_size':args.batch_size,'threads':args.threads,
              'lr':args.lr,'min_lr':args.min_lr,'schedule':'cosine'}
    if (type(protocol.get('schema_version')) is not int or protocol['schema_version']!=1
            or protocol.get('target')!=target or protocol.get('dataset_manifest_sha256')!=args.manifest_sha256
            or not isinstance(policy,dict) or any(policy.get(k)!=v for k,v in expected.items())
            or policy.get('include_initial') is not False):
        raise ValueError('Require a separately preregistered8bucket protocol bound to every effective setting')
    if policy.get('initial_net_sha256')!=sha256(args.initial_net):
        raise ValueError('Preregistered initial network hash differs')
    return target


def dense_features(indices):
    if indices.dtype != np.int16 or indices.ndim != 3 or tuple(indices.shape[1:]) != (2,32):
        raise ValueError('Prepared indices must be int16[N,2,32]')
    if ((indices < -1) | (indices >= 768)).any(): raise ValueError('Feature index out of range')
    ordered = np.sort(indices, axis=2)
    if ((ordered[:,:,1:] == ordered[:,:,:-1]) & (ordered[:,:,1:] >= 0)).any():
        raise ValueError('Duplicate piece-square feature')
    tensors = torch.from_numpy(indices.astype(np.int64))
    dense = torch.zeros((len(indices),2,768),dtype=torch.float32)
    dense.scatter_add_(2, tensors.clamp_min(0), (tensors >= 0).to(torch.float32))
    bucket_indices(dense)
    return dense


def load_prepared(data_dir, expected_sha256):
    data_dir = Path(data_dir).resolve(); path = data_dir/'manifest.json'
    if sha256(path) != expected_sha256: raise ValueError('Prepared manifest hash differs')
    manifest = json.loads(path.read_text()); validate_training_manifest(manifest)
    if set(manifest.get('files',{})) != {'train.npz','validation.npz'}:
        raise ValueError('Exactly train/validation prepared arrays are required')
    partitions = []
    for name in ('train.npz','validation.npz'):
        record = manifest['files'][name]; path = data_dir/name
        if sha256(path) != record['sha256']: raise ValueError('Prepared array hash differs')
        with np.load(path,allow_pickle=False) as archive:
            if set(archive.files) != {'features','hce','score','result_stm'}: raise ValueError('Prepared arrays differ')
            arrays = {key:archive[key] for key in archive.files}
        n=record['rows']
        if type(n) is not int or n < 1 or any(len(a)!=n for a in arrays.values()): raise ValueError('Prepared row counts differ')
        if arrays['hce'].dtype!=np.int32 or arrays['score'].dtype!=np.int32 or arrays['result_stm'].dtype!=np.float32:
            raise ValueError('Prepared target dtypes differ')
        if not np.isin(arrays['result_stm'],[0.,.5,1.]).all(): raise ValueError('Invalid STM game result')
        if any(a.ndim!=1 for k,a in arrays.items() if k!='features'): raise ValueError('Prepared scalar dimensions differ')
        # Validate sparse shape/count/duplicates in bounded batches, not one giant dense tensor.
        for begin in range(0,n,1024): dense_features(arrays['features'][begin:begin+1024])
        partitions.append(arrays)
    return (*partitions, manifest)


def train_batch(model, optimizer, features, hce, teacher_cp, result_stm, result_weight=0.4):
    if not math.isfinite(result_weight) or not 0 <= result_weight <= 1:
        raise ValueError('Result weight must be in[0,1]')
    if not torch.isin(result_stm,torch.tensor([0.,.5,1.],device=result_stm.device)).all():
        raise ValueError('Invalid side-to-move game outcomes')
    optimizer.zero_grad(set_to_none=True)
    logits=model(features).flatten()
    target=(1-result_weight)*torch.sigmoid(teacher_cp*K/CP_SCALE)+result_weight*result_stm
    loss=((torch.sigmoid(hce*K/CP_SCALE+logits)-target)**2).mean()
    if not torch.isfinite(loss): raise ValueError('Nonfinite training loss')
    loss.backward(); optimizer.step(); model.project_weights()
    return float(loss.detach())


@torch.no_grad()
def evaluate(model, arrays, batch_size, result_weight):
    total=0.; n=len(arrays['score']); was_training=model.training
    if batch_size<1 or n<1 or not math.isfinite(result_weight) or not 0<=result_weight<=1:
        raise ValueError('Evaluation requires nonempty data, positive batch and valid result weight')
    model.eval()
    try:
        for begin in range(0,n,batch_size):
            end=begin+batch_size; logits=model(dense_features(arrays['features'][begin:end])).flatten()
            hce=torch.from_numpy(arrays['hce'][begin:end].astype(np.float32))
            score=torch.from_numpy(arrays['score'][begin:end].astype(np.float32)); outcome=torch.from_numpy(arrays['result_stm'][begin:end])
            correction=torch.trunc(torch.clamp(logits*CP_SCALE/K,-30000,30000))
            combined=torch.clamp(hce+correction,-COMBINED_CP_LIMIT,COMBINED_CP_LIMIT)
            target=(1-result_weight)*torch.sigmoid(score*K/CP_SCALE)+result_weight*outcome
            total+=float(((torch.sigmoid(combined*K/CP_SCALE).double()-target.double())**2).sum())
    finally:
        model.train(was_training)
    if not math.isfinite(total): raise ValueError('Nonfinite validation metric')
    return total/n


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    for name in ('data-dir','manifest-sha256','initial-net','protocol','out'): parser.add_argument('--'+name,required=True)
    parser.add_argument('--epochs',type=int,default=8);parser.add_argument('--batch-size',type=int,default=1024)
    parser.add_argument('--threads',type=int,default=4);parser.add_argument('--seed',type=int,default=20261023)
    parser.add_argument('--lr',type=float,default=.0003);parser.add_argument('--min-lr',type=float,default=.000003)
    parser.add_argument('--result-weight',type=float,default=.4)
    args=parser.parse_args(argv)
    if (min(args.epochs,args.batch_size,args.threads)<1 or args.seed<0
            or not all(math.isfinite(v) for v in (args.lr,args.min_lr))
            or not 0<args.lr or not 0<=args.min_lr<=args.lr):
        raise ValueError('Invalid positive training settings')
    if not math.isfinite(args.result_weight) or not 0<=args.result_weight<=1: raise ValueError('Invalid blend')
    protocol_path=Path(args.protocol);protocol_sha=sha256(protocol_path);protocol=json.loads(protocol_path.read_text())
    target=validate_training_protocol(protocol,args)
    torch.set_num_threads(args.threads);torch.manual_seed(args.seed)
    train,validation,manifest=load_prepared(args.data_dir,args.manifest_sha256)
    if manifest.get('target')!=target: raise ValueError('Frozen data target differs')
    model=BucketedNNUE(qat=True);initial=load_initial(model,args.initial_net)
    out=Path(args.out);out.mkdir(parents=True,exist_ok=False)
    optimizer=torch.optim.Adam(model.parameters(),lr=args.lr);rng=np.random.default_rng(args.seed)
    summary={'status':'running','model':'forge_residual_buckets8_v1','initial_net':initial,'manifest_sha256':args.manifest_sha256,
             'protocol_sha256':protocol_sha,'config':vars(args),'initial_validation_mse':evaluate(model,validation,args.batch_size,args.result_weight),
             'epochs':[],'selection_rule':'earliest minimum trained-epoch blended validation MSE; initialexcluded',
             'final_audit_used':False,'elo':'unproven'}
    for epoch in range(args.epochs):
        progress=epoch/(args.epochs-1) if args.epochs>1 else 0.
        lr=args.min_lr+(args.lr-args.min_lr)*(1+math.cos(math.pi*progress))/2
        for group in optimizer.param_groups:group['lr']=lr
        model.train();order=rng.permutation(len(train['score']));loss_sum=0.
        for begin in range(0,len(order),args.batch_size):
            idx=order[begin:begin+args.batch_size]
            loss=train_batch(model,optimizer,dense_features(train['features'][idx]),
                torch.from_numpy(train['hce'][idx].astype(np.float32)),torch.from_numpy(train['score'][idx].astype(np.float32)),
                torch.from_numpy(train['result_stm'][idx]),args.result_weight)
            loss_sum+=loss*len(idx)
        stem=out/f'epoch-{epoch+1:04d}';metadata=export_bucketed(model,stem)
        atomic_write(stem.with_suffix('.pt'),lambda stream:torch.save({'state_dict':cpu_copy(model.state_dict()),'model':'forge_residual_buckets8_v1','config':vars(args)},stream))
        row={'epoch':epoch+1,'lr':lr,'training_target_mse':loss_sum/len(order),'target_mse_combined':evaluate(model,validation,args.batch_size,args.result_weight),'export':metadata}
        summary['epochs'].append(row);print(json.dumps(row),flush=True)
    if sha256(protocol_path)!=protocol_sha or sha256(args.initial_net)!=initial['sha256']:
        raise ValueError('Frozen protocol or initial network changed')
    if sha256(Path(args.data_dir)/'manifest.json')!=args.manifest_sha256: raise ValueError('Prepared manifest changed')
    for name,record in manifest['files'].items():
        if sha256(Path(args.data_dir)/name)!=record['sha256']:raise ValueError('Frozen arrays changed')
    summary['best_epoch']=min(summary['epochs'],key=lambda row:(row['target_mse_combined'],row['epoch']))['epoch']
    summary['status']='completed';summary['input_integrity']='passed'
    atomic_write(out/'summary.json',lambda stream:stream.write((json.dumps(summary,indent=2)+'\n').encode()))
    return 0


if __name__ == '__main__': raise SystemExit(main())
