#!/usr/bin/env python3
"""S-A4: widen a Forge-768 H-unit network include file to 2H units (default 256 -> 512), function-preserving.

  python -I -B widen_net_sa4.py --net src/nnue_weights.inc --mode split --out h512_widened.inc [--pt h512_widened.pt]

--mode split (exact in the engine's integer arithmetic): unit j and its copy j+H get the same W1 column and B1; each
  output weight w is split into ceil(w/2) (unit j) + (w - ceil(w/2)) (copy), for both perspectives. The copies' int32
  accumulators are identical, so sum_h q_h * w2'_h == sum_j q_j * w2_j exactly: the NnueInt16 evaluation of the 2H net
  equals the H net's on every position (same bench nodes with NnueInt16 ON). The float path only differs by float
  rounding order. A test net for parity and NPS at the new width with the lock's search tree.
--mode zero (a warm start for training): units 0..H-1 = the source net, H new units with W1 ~ N(0, 0.02) on the 1/4096
  grid (seeded; the trainer's own init), B1 0 and output weights 0, so the function is the source net's exactly; the
  new units learn from their output weights (no duplicate-unit symmetry).
--mode copy: no widening (the source net; e.g. the lock as an H state_dict to compare losses with a widened warm start).
--pt writes the same weights as a bare float32 state_dict (ft.weight [2H,768], ft.bias, out.weight [1,4H], out.bias) for
  the trainer's --init-weights (needs torch). Values are exact grid multiples of 1/4096, so the trainer's QAT export of an
  unchanged net reproduces the .inc.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

import numpy as np


def read_inc(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")

    def arr(name):
        m = re.search(name + r"\[(\d+)\]\s*=\s*\{([^}]*)\}", text, re.S)
        values = np.array([int(x) for x in m.group(2).replace("\n", " ").split(",") if x.strip()], np.int64)
        if len(values) != int(m.group(1)):
            raise ValueError(f"{path}: {name} length")
        return values

    w1, b1, w2 = arr("NnueW1"), arr("NnueB1"), arr("NnueW2")
    b2 = int(re.search(r"NnueB2\s*=\s*(-?\d+)", text).group(1))
    residual = re.search(r"#define FORGE_NNUE_RESIDUAL\s+(\d)", text)
    h = len(b1)
    return {"w1": w1.reshape(768, h), "b1": b1, "w2": w2, "b2": b2, "hidden": h,
            "residual": bool(int(residual.group(1))) if residual else False}


def widen(net: dict, mode: str, seed: int) -> dict:
    h = net["hidden"]
    w1, b1, w2 = net["w1"], net["b1"], net["w2"]
    if mode == "split":
        w1n = np.concatenate([w1, w1], axis=1)
        b1n = np.concatenate([b1, b1])
        halves = []
        for part in (w2[:h], w2[h:]):
            a = -((-part) // 2)  # ceil(w/2)
            halves.append(np.concatenate([a, part - a]))
        w2n = np.concatenate(halves)
    elif mode == "copy":  # no widening: the source net itself (e.g. as a state_dict for comparisons)
        return {k: (v.copy() if isinstance(v, np.ndarray) else v) for k, v in net.items()}
    elif mode == "zero":
        rng = np.random.default_rng(seed)
        new = np.sign(z := rng.normal(0.0, 0.02, (768, h)) * 4096.0) * np.floor(np.abs(z) + 0.5)
        w1n = np.concatenate([w1, new.astype(np.int64)], axis=1)
        b1n = np.concatenate([b1, np.zeros(h, np.int64)])
        w2n = np.concatenate([w2[:h], np.zeros(h, np.int64), w2[h:], np.zeros(h, np.int64)])
    else:
        raise ValueError(mode)
    out = {"w1": w1n, "b1": b1n, "w2": w2n, "b2": net["b2"], "hidden": 2 * h, "residual": net["residual"]}
    for name in ("w1", "b1", "w2"):
        if np.abs(out[name]).max() > 32767:
            raise ValueError(f"{name} outside int16")
    return out


def write_inc(net: dict, path: Path, note: str) -> None:
    h = net["hidden"]
    lines = [f"// Generated by widen_net_sa4.py ({note}); Forge-768 network.",
             "#include <cstdint>", f"#define FORGE_NNUE_RESIDUAL {1 if net['residual'] else 0}",
             f"static_assert(forge::nnue::InputCount == 768 && forge::nnue::HiddenSize == {h},",
             '              "NNUE shape mismatch; rebuild with the correct FORGE_NNUE_HIDDEN");',
             'static_assert(forge::nnue::SigmoidK == 2.25F, "NNUE output scale mismatch");',
             'static_assert(forge::nnue::WeightScale == 4096.0F && forge::nnue::OutputScale == 4096.0F,',
             '              "NNUE quantization scale mismatch");']
    for name, v in (("NnueW1", net["w1"].ravel()), ("NnueB1", net["b1"]), ("NnueW2", net["w2"])):
        lines.append(f"static const std::int16_t {name}[{len(v)}] = {{")
        lines.extend("  " + ", ".join(map(str, v[i:i + 24])) + "," for i in range(0, len(v), 24))
        lines.append("};")
    lines.append(f"static const std::int16_t NnueB2 = {int(net['b2'])};")
    with open(path, "x", encoding="ascii", newline="\n") as out:
        out.write("\n".join(lines) + "\n")


def write_pt(net: dict, path: Path) -> None:
    import torch
    h = net["hidden"]
    sd = {"ft.weight": torch.from_numpy((net["w1"].T / 4096.0).astype(np.float32)).contiguous(),
          "ft.bias": torch.from_numpy((net["b1"] / 4096.0).astype(np.float32)),
          "out.weight": torch.from_numpy((net["w2"] / 4096.0).astype(np.float32)).reshape(1, 2 * h),
          "out.bias": torch.tensor([net["b2"] / 4096.0], dtype=torch.float32)}
    with open(path, "xb") as out:
        torch.save(sd, out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--net", type=Path, required=True)
    ap.add_argument("--mode", choices=["split", "zero", "copy"], required=True)
    ap.add_argument("--seed", type=int, default=512)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--pt", type=Path)
    a = ap.parse_args(argv)
    src = read_inc(a.net)
    wide = widen(src, a.mode, a.seed)
    note = f"--mode {a.mode} of {a.net.name}, md5 {hashlib.md5(a.net.read_bytes()).hexdigest()}"
    write_inc(wide, a.out, note + (f", seed {a.seed}" if a.mode == "zero" else ""))
    if a.pt:
        write_pt(wide, a.pt)
    a1 = np.abs(wide["w1"])
    info = {"source": str(a.net), "source_hidden": src["hidden"], "hidden": wide["hidden"], "mode": a.mode,
            "out": str(a.out), "out_sha256": hashlib.sha256(a.out.read_bytes()).hexdigest(),
            "max_abs": {k: int(np.abs(wide[k]).max()) for k in ("w1", "b1", "w2")},
            "lane_bound": int((np.abs(wide["b1"]) + a1.sum(axis=0)).max() + 4 * a1.max()),
            "w2_sum_preserved": bool(all(np.array_equal(wide["w2"][s * wide["hidden"]:(s * wide["hidden"]) + src["hidden"]]
                                                        + (wide["w2"][s * wide["hidden"] + src["hidden"]:(s + 1) * wide["hidden"]]
                                                           if a.mode == "split" else 0), src["w2"][s * src["hidden"]:(s + 1) * src["hidden"]])
                                         for s in (0, 1)))}
    if a.pt:
        info["pt"] = str(a.pt)
        info["pt_sha256"] = hashlib.sha256(a.pt.read_bytes()).hexdigest()
    print(json.dumps(info, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
