def random_inc(path: Path, seed: int):
    rng = np.random.default_rng(seed)
    w1, b1, w2 = rng.integers(-3000, 3000, 768 * 256), rng.integers(-500, 500, 256), rng.integers(-9000, 9000, 512)
    b2 = int(rng.integers(-300, 300))
    path.write_bytes(tool.render_inc(HEAD, w1, b1, w2, b2))
    return w1, b1, w2, b2


class Averaging(unittest.TestCase):
    def test_single_file_average_is_byte_identical(self):
        with tempfile.TemporaryDirectory() as tmp:
            a = Path(tmp) / "a.inc"
            random_inc(a, 1)
            self.assertEqual(tool.average_incs([a]), a.read_bytes())

    def test_two_file_average_rounds_half_away_from_zero(self):
        with tempfile.TemporaryDirectory() as tmp:
            a, b = Path(tmp) / "a.inc", Path(tmp) / "b.inc"
            wa, ba, va, ca = random_inc(a, 2)
            wb, bb, vb, cb = random_inc(b, 3)
            out = tool.parse_inc_bytes(tool.average_incs([a, b])) if hasattr(tool, "parse_inc_bytes") else None
            p = Path(tmp) / "avg.inc"
            p.write_bytes(tool.average_incs([a, b]))
            got = tool.parse_inc(p)
            s = wa + wb                                     # mean*4096 = s/2: .5 cases round away from zero
            expect = np.where(s % 2 == 0, s // 2, np.sign(s) * ((np.abs(s) + 1) // 2))
            self.assertTrue(np.array_equal(got["w1"], expect))
            self.assertEqual(got["head"], HEAD)

    def test_bin_path_quantizes_like_export_forge(self):
        with tempfile.TemporaryDirectory() as tmp:
            rng = np.random.default_rng(4)
            arrays = [rng.normal(0, 0.05, 768 * 256), rng.normal(0, 0.05, 256), rng.normal(0, 0.3, 512), rng.normal(0, 0.05, 1)]
            binp = Path(tmp) / "x.bin"
            binp.write_bytes(b"".join(np.asarray(v, "<f4").tobytes() for v in arrays))
            template = Path(tmp) / "t.inc"
            random_inc(template, 5)
            got = tool.parse_inc_from_bytes(tool.average_bins([binp], template)) if hasattr(tool, "parse_inc_from_bytes") else None
            out = Path(tmp) / "o.inc"
            out.write_bytes(tool.average_bins([binp], template))
            q = tool.parse_inc(out)
            f32 = np.frombuffer(binp.read_bytes(), "<f4").astype(np.float64)
            ref = np.sign(f32 * 4096) * np.floor(np.abs(f32 * 4096) + 0.5)
            self.assertTrue(np.array_equal(q["w1"], ref[:768 * 256]))
            self.assertEqual(q["b2"], int(ref[-1]))

    @unittest.skipUnless(E12.is_dir(), "no e12 checkpoint dir")
    def test_real_files_reproduce_their_md5(self):
        for name in ("resid_h256_e12_e_ep02.inc", "resid_h256_e12_e_ep11.inc", "resid_h256_e12_e_ep12.inc"):
            path = E12 / name
            self.assertEqual(hashlib.md5(tool.average_incs([path])).hexdigest(), hashlib.md5(path.read_bytes()).hexdigest(), name)


class Scoring(unittest.TestCase):
    def test_score_matches_a_direct_formula(self):
        with tempfile.TemporaryDirectory() as tmp:
            tmp = Path(tmp)
            w1, b1, w2, b2 = random_inc(tmp / "n.inc", 6)
            net = tool.parse_inc(tmp / "n.inc")
            rng = np.random.default_rng(7)
            n = 50
            boards = np.zeros((n, 32), np.uint8)
            for i in range(n):
                codes = np.zeros(64, np.int64)
                sq = rng.choice(64, 10, replace=False)
                codes[sq] = rng.integers(1, 13, 10)
                boards[i] = (codes[0::2] | (codes[1::2] << 4)).astype(np.uint8)
            score = rng.integers(-800, 800, n).astype("<i2")
            meta = (rng.integers(0, 2, n) | (rng.integers(0, 3, n) << 1)).astype(np.uint8)
            hce = rng.integers(-400, 400, n).astype("<i2")
            hdr = lambda m: m + (1).to_bytes(4, "little") + n.to_bytes(8, "little")
            (tmp / "h.pos").write_bytes(hdr(b"FPOS") + boards.tobytes() + score.tobytes() + meta.tobytes())
            (tmp / "h.hce").write_bytes(hdr(b"FHCE") + hce.tobytes())
            data = tool.read_pos(tmp / "h.pos", tmp)
            got = tool.score_net(net, data)
            stm = (meta & 1).astype(np.int64)
            logit = tool.net_logit(net, boards, stm) + hce * 2.25 / 400
            pred = 1 / (1 + np.exp(-logit))
            white = (meta >> 1) * 0.5
            res = np.where(stm == 0, white, 1 - white)
            teacher = 1 / (1 + np.exp(-np.clip(score * 2.25 / 400, -40, 40)))
            for b in (1.0, 0.6, 0.8):
                self.assertAlmostEqual(got[f"mse_b{b}"], float(np.mean((pred - (b * teacher + (1 - b) * res)) ** 2)), places=12)

    def test_subset_is_deterministic(self):
        with tempfile.TemporaryDirectory() as tmp:
            tmp = Path(tmp)
            n = 37
            hdr = lambda m: m + (1).to_bytes(4, "little") + n.to_bytes(8, "little")
            rng = np.random.default_rng(8)
            for name in ("a", "b"):
                (tmp / f"{name}.pos").write_bytes(hdr(b"FPOS") + rng.integers(0, 255, 32 * n, dtype=np.uint8).tobytes()
                                                + rng.integers(-99, 99, n).astype("<i2").tobytes() + rng.integers(0, 5, n, dtype=np.uint8).tobytes())
                (tmp / f"{name}.hce").write_bytes(hdr(b"FHCE") + rng.integers(-99, 99, n).astype("<i2").tobytes())
            r1 = tool.write_subset([tmp / "a.pos", tmp / "b.pos"], tmp, 5, tmp / "s1")
            r2 = tool.write_subset([tmp / "a.pos", tmp / "b.pos"], tmp, 5, tmp / "s2")
            self.assertEqual((r1["pos_md5"], r1["hce_md5"]), (r2["pos_md5"], r2["hce_md5"]))
            self.assertEqual(r1["rows"], len(range(0, 2 * n, 5)))


class Checkpoints(unittest.TestCase):
    """.pt inputs (resume rework: any 2+ .pt files of one run); needs torch, skipped without it."""

    def test_pt_path_equals_bin_path_and_refuses_mixed_runs(self):
        try:
            import torch
        except ImportError:
            self.skipTest("torch not installed")
        with tempfile.TemporaryDirectory() as tmp:
            tmp = Path(tmp)
            template = tmp / "t.inc"
            random_inc(template, 9)
            cfg = {"hidden": 256, "residual": True, "features": "forge768-relative-pieces-rank-flip", "epochs": 48,
                   "steps_per_epoch": 16770}
            pts, bins = [], []
            for seed in (11, 12):
                g = torch.Generator().manual_seed(seed)
                model = {"ft.weight": torch.randn(256, 768, generator=g) * 0.05, "ft.bias": torch.randn(256, generator=g) * 0.05,
                         "out.weight": torch.randn(1, 512, generator=g) * 0.3, "out.bias": torch.randn(1, generator=g) * 0.05}
                pt = tmp / f"e{seed}.pt"
                torch.save({"config": cfg, "model": model, "optimizer": {}}, str(pt))
                pts.append(pt)
                b = tmp / f"e{seed}.bin"   # the trainer's float32 export order: W1^T (768 x H), B1, W2, B2
                b.write_bytes(b"".join(np.asarray(v, "<f4").tobytes() for v in (
                    model["ft.weight"].numpy().T.reshape(-1), model["ft.bias"].numpy(), model["out.weight"].numpy().reshape(-1),
                    model["out.bias"].numpy())))
                bins.append(b)
            self.assertEqual(tool.average_pts(pts, template), tool.average_bins(bins, template))
            self.assertEqual(tool.average_pts(pts[:1], template), tool.average_bins(bins[:1], template))
            other = tmp / "other.pt"
            torch.save({"config": dict(cfg, epochs=24), "model": torch.load(str(pts[0]), weights_only=True)["model"]}, str(other))
            with self.assertRaises(ValueError):
                tool.average_pts([pts[0], other], template)


