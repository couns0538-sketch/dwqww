#!/usr/bin/env python3
"""S-C4: widen a Forge-768 H256 nnue_weights.inc to hidden size H by zero padding (function-preserving).

Layout (src/nnue.cpp of the lock): NnueW1[InputCount][HiddenSize] (feature-major rows), NnueB1[HiddenSize],
NnueW2[2 * HiddenSize] = [side-to-move half | opponent half], NnueB2 scalar. New hidden units get zero W1 columns,
zero B1 and zero W2 entries in both halves, so their accumulators stay exactly 0.0, SCReLU(0) = 0, and the output
sum gains only +0.0 terms: the widened net evaluates identically and the search tree is unchanged, which makes the
node counts a check of the measurement. The shape static_assert is rewritten to the new H; every other line is copied.

usage: python -I -B opus_sc4_widen_inc.py --inc <H256 nnue_weights.inc> --hidden H --out <new file>
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ARRAY = re.compile(r"static const std::int16_t (NnueW1|NnueB1|NnueW2)\[(\d+)\] = \{(.*?)\};", re.S)


def parse(text: str) -> dict[str, list[int]]:
    arrays = {}
    for name, n, body in ARRAY.findall(text):
        vals = [int(x) for x in body.replace("\n", " ").split(",") if x.strip()]
        if len(vals) != int(n):
            raise ValueError(f"{name}: {len(vals)} values, declared {n}")
        arrays[name] = vals
    if set(arrays) != {"NnueW1", "NnueB1", "NnueW2"}:
        raise ValueError(f"arrays found: {sorted(arrays)}")
    return arrays


def widen(arrays: dict[str, list[int]], h_old: int, h_new: int, inputs: int = 768) -> dict[str, list[int]]:
    if h_new < h_old:
        raise ValueError("can only widen")
    w1, b1, w2 = arrays["NnueW1"], arrays["NnueB1"], arrays["NnueW2"]
    if len(w1) != inputs * h_old or len(b1) != h_old or len(w2) != 2 * h_old:
        raise ValueError("input shape does not match h_old")
    pad = [0] * (h_new - h_old)
    nw1 = []
    for f in range(inputs):
        nw1 += w1[f * h_old:(f + 1) * h_old] + pad
    return {"NnueW1": nw1, "NnueB1": b1 + pad, "NnueW2": w2[:h_old] + pad + w2[h_old:] + pad}


def fmt(name: str, vals: list[int]) -> str:
    rows = [", ".join(str(v) for v in vals[i:i + 16]) for i in range(0, len(vals), 16)]
    return f"static const std::int16_t {name}[{len(vals)}] = {{\n  " + ", \n  ".join(rows) + ", \n};"


def main(argv=None) -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--inc", type=Path, required=True)
    ap.add_argument("--hidden", type=int, required=True)
    ap.add_argument("--h-old", type=int, default=256)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args(argv)
    if a.out.exists():
        raise SystemExit(f"refusing to overwrite {a.out}")
    text = a.inc.read_text(encoding="utf-8")
    arrays = parse(text)
    new = widen(arrays, a.h_old, a.hidden)
    out = text
    for name in ("NnueW1", "NnueB1", "NnueW2"):
        m = re.search(rf"static const std::int16_t {name}\[\d+\] = \{{.*?\}};", out, re.S)
        out = out[:m.start()] + fmt(name, new[name]) + out[m.end():]
    old_assert = f"forge::nnue::HiddenSize == {a.h_old}"
    if out.count(old_assert) != 1:
        raise SystemExit("shape static_assert not found exactly once")
    out = out.replace(old_assert, f"forge::nnue::HiddenSize == {a.hidden}")
    out = out.replace("// Generated by train_resid.py; Forge-768 network.",
                      f"// Generated by train_resid.py; Forge-768 network. Zero-padded from H{a.h_old} to H{a.hidden} "
                      "by opus_sc4_widen_inc.py (function-preserving; S-C4 NPS measurement only).", 1)
    back = parse(out)
    for f in range(768):  # the original weights sit unchanged in the first h_old columns
        assert back["NnueW1"][f * a.hidden:f * a.hidden + a.h_old] == arrays["NnueW1"][f * a.h_old:(f + 1) * a.h_old]
        assert not any(back["NnueW1"][f * a.hidden + a.h_old:(f + 1) * a.hidden])
    assert back["NnueW2"][:a.h_old] == arrays["NnueW2"][:a.h_old]
    assert back["NnueW2"][a.hidden:a.hidden + a.h_old] == arrays["NnueW2"][a.h_old:]
    a.out.write_bytes(out.encode("utf-8"))
    print(f"wrote {a.out}: H{a.h_old} -> H{a.hidden}, W1 {len(back['NnueW1'])}, B1 {len(back['NnueB1'])}, W2 {len(back['NnueW2'])}; round-trip OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
