#!/usr/bin/env python3
"""int8_convert.py - quantize the trial_w6 output layer to int8 for the NnueInt8Vnni path (own code, 2026-11-06).

usage: python -I -B int8_convert.py <nnue_weights.inc> <out nnue_int8_weights.inc>

Input: the lock's src/nnue_weights.inc (int16 W1/B1/W2/B2 at 1/4096; the engine's float net = these / 4096).
Output: a small include with the int8 output weights W2q[512] and the integer constants of the scheme in
opus_nnue_int8_vnni/QUANT_SCHEME.md. The feature-transformer weights are not written: the engine derives them at start
from the same int16 arrays with FT_SHIFT (W1q = (W1 + 8) >> 4), exactly as ft_quant() below does.
Refuses to overwrite the output. Prints the statistics QUANT_SCHEME.md quotes.
"""
import hashlib
import re
import sys

HIDDEN = 256
INPUTS = 768
FT_SHIFT = 4          # FT weights 1/4096 -> 1/256 (int16 range proof: BOUNDS.md)
ACT_MAX = 255         # clip of the int16 accumulator before squaring
W2Q_MAX = 127         # int8 output weights in [-127, 127]


def parse(text, name):
    m = re.search(r'%s\[(\d+)\]\s*=\s*\{([^}]*)\}' % name, text)
    if not m:
        raise SystemExit('int8_convert: array %s not found' % name)
    vals = [int(x) for x in m.group(2).replace('\n', ' ').split(',') if x.strip()]
    if len(vals) != int(m.group(1)):
        raise SystemExit('int8_convert: %s has %d values, declared %s' % (name, len(vals), m.group(1)))
    return vals


def scalar(text, name):
    m = re.search(r'%s\s*=\s*(-?\d+)\s*;' % name, text)
    if not m:
        raise SystemExit('int8_convert: scalar %s not found' % name)
    return int(m.group(1))


def ft_quant(v):
    """int16 at 1/4096 -> int16 at 1/256, round half up (floor((v + 8) / 16)); = C++ (v + 8) >> 4 (arithmetic)."""
    return (v + (1 << (FT_SHIFT - 1))) >> FT_SHIFT


def w2_quant(v, maxabs):
    """round half away from zero of v * 127 / maxabs, in integers only."""
    q = (abs(v) * 2 * W2Q_MAX + maxabs) // (2 * maxabs)
    return q if v >= 0 else -q


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    src, dst = sys.argv[1], sys.argv[2]
    raw = open(src, 'rb').read()
    text = raw.decode('ascii')
    w1, b1, w2 = parse(text, 'NnueW1'), parse(text, 'NnueB1'), parse(text, 'NnueW2')
    b2 = scalar(text, 'NnueB2')
    if len(w1) != INPUTS * HIDDEN or len(b1) != HIDDEN or len(w2) != 2 * HIDDEN:
        raise SystemExit('int8_convert: unexpected sizes')
    maxabs = max(abs(v) for v in w2)
    w2q = [w2_quant(v, maxabs) for v in w2]
    assert all(-W2Q_MAX <= q <= W2Q_MAX for q in w2q)
    # rounding error of the output weights in float units (w2 / 4096) and the FT weights (1/4096 units)
    sw = W2Q_MAX * 4096.0 / maxabs                      # int8 units per float unit
    err_w2 = [abs(q / sw - v / 4096.0) for q, v in zip(w2q, w2)]
    err_ft = [abs(ft_quant(v) * 16 - v) for v in w1]
    sha = hashlib.sha256(raw).hexdigest()
    lines = [
        '// Generated by opus_nnue_int8_vnni/tools/int8_convert.py (own code) - do not edit.',
        '// Input nnue_weights.inc sha256 %s' % sha,
        '// Scheme: opus_nnue_int8_vnni/QUANT_SCHEME.md. W2q = round(W2 * 127 / %d), half away from zero.' % maxabs,
        '#pragma once',
        '#include <cstdint>',
        'static_assert(forge::nnue::HiddenSize == %d, "nnue_int8_weights.inc was made for another HiddenSize");' % HIDDEN,
        'constexpr int NnueInt8W2MaxAbs = %d;   // max |W2| of the int16 output weights (1/4096 units)' % maxabs,
        'constexpr int NnueInt8B2 = %d;          // = NnueB2 (1/4096 units)' % b2,
        'static const std::int8_t NnueInt8W2[%d] = {' % (2 * HIDDEN),
    ]
    for i in range(0, len(w2q), 16):
        lines.append('    ' + ', '.join('%d' % q for q in w2q[i:i + 16]) + ',')
    lines.append('};')
    out = ('\n'.join(lines) + '\n').encode('ascii')
    try:
        with open(dst, 'xb') as f:
            f.write(out)
    except FileExistsError:
        raise SystemExit('int8_convert: %s exists (never overwritten)' % dst)
    print('input sha256 %s' % sha)
    print('W2 int16 min %d max %d maxabs %d; W2q min %d max %d, zeros %d of %d' % (
        min(w2), max(w2), maxabs, min(w2q), max(w2q), sum(1 for q in w2q if q == 0), len(w2q)))
    print('W2 rounding error (float units): max %.5f mean %.5f; one int8 step = %.5f' % (
        max(err_w2), sum(err_w2) / len(err_w2), 1.0 / sw))
    print('FT rounding error (1/4096 units): max %d mean %.3f (step 16)' % (max(err_ft), sum(err_ft) / len(err_ft)))
    b1q = [ft_quant(v) for v in b1]
    print('B1q min %d max %d; W1q min %d max %d' % (min(b1q), max(b1q), min(ft_quant(v) for v in w1),
                                                     max(ft_quant(v) for v in w1)))
    print('output md5 %s -> %s' % (hashlib.md5(out).hexdigest(), dst))


if __name__ == '__main__':
    main()
