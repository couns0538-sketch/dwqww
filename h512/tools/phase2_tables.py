#!/usr/bin/env python
"""phase2_tables.py - JOB E phase 2 (2026-11-11): Markdown tables of the phase-2 training results. Own code.

  phase2_tables.py [--work _work] [--res h512/results/phase2] > h512/results/phase2/tables.md

Every number is read from the runs' own metrics.jsonl files and from the score files in the results folder; nothing
is typed in by hand. Loss = mean squared error against the blend-0.6 target on the named set (lower is better).
"""
import argparse
import glob
import json
import os


def rows(path):
    if not os.path.isfile(path):
        return []
    return [json.loads(line) for line in open(path, encoding="utf-8")]


def f6(x):
    return "" if x is None else f"{x:.6f}"


def sc(e, name, key="mse_b0.6"):
    return e["scores"].get(name, {}).get(key)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--work", default="_work")
    ap.add_argument("--res", default="h512/results/phase2")
    a = ap.parse_args()
    out = []
    out.append("# JOB E phase 2: training tables (generated by h512/tools/phase2_tables.py)\n")
    out.append("Loss = MSE against the blend-0.6 target, exported integer net. `selection` = 2,000,000 unseen rows (shards 013/014); "
               "`training rows` = 2,000,000 rows of the training set; `FB2 200k` = FB2's old holdout (shards 013/014).\n")

    # ---- A: the run without decay, continued from 2.0B
    out.append("## A. Run without weight decay, continued from 2.0B (paused at 4.0B)\n")
    out.append("| Presentations | Stage | Checkpoint | Learning rate | Selection | FB2 200k |")
    out.append("|---:|---|---|---:|---:|---:|")
    for e in rows(os.path.join(a.work, "runs", "main", "metrics.jsonl")) + rows(os.path.join(a.work, "runs", "phase2", "metrics.jsonl")):
        out.append(f"| {e['seen']:,} | {e['stage']} | {e['reason']} | {e['lr']:.2e} | {f6(e['metric'])} | {f6(sc(e, 'fb2_200k'))} |")
    out.append("")

    # ---- B: weight-decay pilot
    out.append("## B. Weight-decay pilot: the 1.0B to 2.0B cycle repeated with decay on `w1`\n")
    arms = [("W0", "0 (control)"), ("W1", "0.1"), ("W2", "1.0"), ("W3", "10")]
    data = {arm: rows(os.path.join(a.work, "runs", "wd", arm, "metrics.jsonl")) for arm, _ in arms}
    seens = sorted({e["seen"] for r in data.values() for e in r})
    out.append("Selection loss:\n")
    out.append("| Presentations | " + " | ".join(f"{arm} decay {lam}" for arm, lam in arms) + " |")
    out.append("|---:|" + "---:|" * len(arms))
    for s in seens:
        cells = []
        for arm, _ in arms:
            m = [e["metric"] for e in data[arm] if e["seen"] == s]
            cells.append(f6(m[-1]) if m else "")
        out.append(f"| {s:,} | " + " | ".join(cells) + " |")
    out.append("")
    out.append("At the 2.0B stage end:\n")
    out.append("| Arm | Decay | Selection | Training rows | Gap | FB2 200k | Selection, teacher only (blend 1.0) | Largest abs. w1 (int16) |")
    out.append("|---|---:|---:|---:|---:|---:|---:|---:|")
    for arm, lam in arms:
        ends = [e for e in data[arm] if e["stage"] == "S2" and e["stage_end"]]
        if not ends:
            continue
        e = ends[-1]
        tr = sc(e, "train_sample_2m")
        out.append(f"| {arm} | {lam} | {f6(e['metric'])} | {f6(tr)} | {f6(e['metric'] - tr) if tr else ''} | {f6(sc(e, 'fb2_200k'))} | "
                   f"{f6(sc(e, 'select_2m', 'mse_b1.0'))} | {e['max_w1']} |")
    out.append("")

    # ---- C: continuation arms
    for d in sorted(glob.glob(os.path.join(a.work, "runs", "arms", "*"))):
        name = os.path.basename(d)
        r = rows(os.path.join(d, "metrics.jsonl"))
        if not r:
            continue
        out.append(f"## C. Arm `{name}`\n")
        has_ema = any("ema" in e for e in r)
        head = "| Presentations | Stage | Checkpoint | Learning rate | Selection | Training rows | Gap | FB2 200k |"
        line = "|---:|---|---|---:|---:|---:|---:|---:|"
        if has_ema:
            tags = sorted({t for e in r for t in e.get("ema", {})})
            head += " " + " | ".join(f"avg {t}" for t in tags) + " |"
            line += "---:|" * len(tags)
        out.append(head)
        out.append(line)
        for e in r:
            tr = sc(e, "train_sample_2m")
            row = (f"| {e['seen']:,} | {e['stage']} | {e['reason']} | {e['lr']:.2e} | {f6(e['metric'])} | {f6(tr)} | "
                   f"{f6(e['metric'] - tr) if tr else ''} | {f6(sc(e, 'fb2_200k'))} |")
            if has_ema:
                row += " " + " | ".join(f6(e.get("ema", {}).get(t, {}).get("metric")) for t in tags) + " |"
            out.append(row)
        out.append("")

    # ---- D: score files in the results folder (averages, references on the training-row sample)
    out.append("## D. Single score files\n")
    out.append("| File | Net md5 | Set | Loss (blend 0.6) | Teacher only (blend 1.0) |")
    out.append("|---|---|---|---:|---:|")
    for p in sorted(glob.glob(os.path.join(a.res, "*.json"))):
        try:
            d = json.load(open(p, encoding="utf-8"))
        except ValueError:
            continue
        if "mse_b0.6" in d and "pos" in d:
            out.append(f"| `{os.path.basename(p)}` | `{d.get('net_md5', '')[:12]}` | {os.path.basename(d['pos'])} | {f6(d['mse_b0.6'])} | {f6(d.get('mse_b1.0'))} |")
        elif "hce_baseline" in d:
            pos = os.path.basename(d["holdout"]["pos"])
            out.append(f"| `{os.path.basename(p)}` (HCE alone) | | {pos} | {f6(d['hce_baseline']['mse_b0.6'])} | {f6(d['hce_baseline']['mse_b1.0'])} |")
            for n in d["nets"]:
                out.append(f"| `{os.path.basename(p)}` ({n['net']} + HCE) | `{n['md5'][:12]}` | {pos} | {f6(n['mse_b0.6'])} | {f6(n['mse_b1.0'])} |")
    print("\n".join(out))


if __name__ == "__main__":
    main()
