#!/usr/bin/env python3
"""R5A M3: rebuild the smoke results table from opus_r5/r5a/smoke/*/summary.json.

Writes opus_r5/r5a/smoke/SMOKE_RESULTS.md and replaces the block between <!-- smoke-table --> and
<!-- /smoke-table --> in REPORT.md (bytes kept LF, UTF-8). Crash/legality/clock screen only; the ON score column is
printed for completeness and is not a strength measurement.
usage: smoke_table.py <r5a dir>
"""
import glob
import json
import os
import sys

R5A = sys.argv[1]
ORDER = ["corrmargins1", "corrext1", "corrhistplus2", "corrhistplus4", "corrhistplus6", "netscale99", "histrework1",
         "histrework3"]


def main():
    rows = []
    found = {os.path.basename(os.path.dirname(p)): p for p in glob.glob(os.path.join(R5A, "smoke", "*", "summary.json"))}
    for name in ORDER + sorted(set(found) - set(ORDER)):
        if name not in found:
            continue
        s = json.load(open(found[name], encoding="utf-8"))
        f = s["failure_counts"]
        st = s.get("stop_stress") or {}
        stress = f"{st.get('completed', 0)}/{st.get('iterations', 0)}, {len(st.get('problems', []))} problems" if st else "skipped"
        term = ", ".join(f"{k} {v}" for k, v in sorted(s["terminations"].items(), key=lambda kv: -kv[1]))
        rows.append(f"| {name} | `{' '.join(s['on_options'])}` | {s['games_played']}/{s['games_planned']} | {f['illegal']} | "
                    f"{f['crash']} | {f['time_loss']} | {f['missing_bestmove']} | {f['error_line']} | {f['echo']} | "
                    f"{stress} | {s['avg_plies']} | {s['near_flags_under_20ms']} | {s['engine_restarts']} | "
                    f"{s['on_score_not_elo']['points']:g}/{s['on_score_not_elo']['games']} | {term} | "
                    f"{s['started']}-{s['finished'].replace(' Vienna', '')} | **{s['verdict']}** |")
    head = ("| config | ON options | games | illegal | crashes | time losses | missing bestmove | ERROR lines | echo "
            "mismatches | go/stop stress | avg plies | clock < 20 ms | engine restarts | ON points (not Elo) | "
            "terminations | time (Vienna) | verdict |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    table = head + "\n" + "\n".join(rows) if rows else "(no smoke results yet)"
    with open(os.path.join(R5A, "smoke", "SMOKE_RESULTS.md"), "w", newline="\n", encoding="utf-8") as fh:
        fh.write("# R5A smoke results (generated by tools/smoke_table.py; crash screen, not strength)\n\n" + table + "\n")
    rp = os.path.join(R5A, "REPORT.md")
    text = open(rp, "rb").read().decode("utf-8")
    a, b = "<!-- smoke-table -->", "<!-- /smoke-table -->"
    if a in text and b in text:
        pre, rest = text.split(a, 1)
        _, post = rest.split(b, 1)
        text = pre + a + "\n" + table + "\n" + b + post
        open(rp, "wb").write(text.encode("utf-8"))
    print(f"{len(rows)} smoke rows")


main()
