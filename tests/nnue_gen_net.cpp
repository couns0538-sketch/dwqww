// nnue_gen_net (opus-sol-SA4): writes a deterministic synthetic Forge-768 network include file of any
// hidden width, for building and testing non-default widths (e.g. H512) without a trained net in the
// repository. Not a playing net: weights are seeded pseudo-random int16 values in realistic ranges
// (accumulators reach both ends of the [0, 4096] clamp).
//   usage: nnue_gen_net <hidden> <seed> <out.inc>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <string>

namespace {

std::uint64_t state = 0;

std::uint64_t next() {
    state += 0x9E3779B97F4A7C15ULL;
    std::uint64_t x = state;
    x = (x ^ (x >> 30)) * 0xBF58476D1CE4E5B9ULL;
    x = (x ^ (x >> 27)) * 0x94D049BB133111EBULL;
    return x ^ (x >> 31);
}

int uniform(int lo, int hi) {  // inclusive
    return lo + static_cast<int>(next() % static_cast<std::uint64_t>(hi - lo + 1));
}

void write_array(std::FILE* out, const char* name, int count, int lo, int hi) {
    std::fprintf(out, "static const std::int16_t %s[%d] = {\n", name, count);
    for (int i = 0; i < count; ++i) {
        std::fprintf(out, "%s%d,", i % 24 == 0 ? "  " : " ", uniform(lo, hi));
        if (i % 24 == 23 || i + 1 == count) std::fprintf(out, "\n");
    }
    std::fprintf(out, "};\n");
}

} // namespace

int main(int argc, char** argv) {
    if (argc != 4) {
        std::fprintf(stderr, "usage: %s <hidden> <seed> <out.inc>\n", argv[0]);
        return 2;
    }
    const int hidden = std::atoi(argv[1]);
    state = std::strtoull(argv[2], nullptr, 10);
    if (hidden <= 0 || hidden % 16 != 0) {
        std::fprintf(stderr, "hidden must be a positive multiple of 16\n");
        return 2;
    }
    std::FILE* out = std::fopen(argv[3], "wb");
    if (out == nullptr) return 3;
    std::fprintf(out, "// Generated by nnue_gen_net (synthetic test network, seed %s); Forge-768 network.\n", argv[2]);
    std::fprintf(out, "#include <cstdint>\n#define FORGE_NNUE_RESIDUAL 1\n");
    std::fprintf(out, "static_assert(forge::nnue::InputCount == 768 && forge::nnue::HiddenSize == %d,\n", hidden);
    std::fprintf(out, "              \"NNUE shape mismatch; rebuild with the correct FORGE_NNUE_HIDDEN\");\n");
    std::fprintf(out, "static_assert(forge::nnue::SigmoidK == 2.25F, \"NNUE output scale mismatch\");\n");
    std::fprintf(out, "static_assert(forge::nnue::WeightScale == 4096.0F && forge::nnue::OutputScale == 4096.0F,\n");
    std::fprintf(out, "              \"NNUE quantization scale mismatch\");\n");
    write_array(out, "NnueW1", 768 * hidden, -320, 320);
    write_array(out, "NnueB1", hidden, -1200, 5200);
    write_array(out, "NnueW2", 2 * hidden, -1500, 1500);
    std::fprintf(out, "static const std::int16_t NnueB2 = %d;\n", uniform(-200, 200));
    return std::fclose(out) == 0 ? 0 : 3;
}
