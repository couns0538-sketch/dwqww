#!/usr/bin/env python3
"""check_s28f43.py -- MY OWN check of seat 28's 28-F43: under CPU contention the clock-limited search
gives the SAME depth, the SAME node count and the same move; only the wall time changes.

They measured `go wtime 6000 btime 6000 winc 60 binc 60`, PC r15 + PC20, Threads 1, Hash 16:
identical depth 18, identical 998,994 nodes, same move in 3 solo runs and 3 runs under a busy loop.

This matters because it is the reassuring counterpart to seat 16's S-F28 (effort varies per move):
if the CLOCK row is stable under load then a loaded machine does not change the chess, only the
timing — which justifies running matches on a busy box.

My harness: fresh process per row, Threads 1, Hash 16, OwnBook false, BOTH clocks always plus the
increments (30-C49), 3 solo + 3 under load. The load is generated by this script itself with N busy
processes (no external dependency). I also compare against `go depth N` to confirm the clock row is
a fixed point rather than the depth cap.

usage: check_s28f43.py OUTDIR [LOAD_PROCS]
"""
import json
import os
import subprocess
import sys
import threading
import time

EXE = "/home/ubuntu/b/pc/forge"
ENV = {k: v for k, v in os.environ.items()
       if k not in ("ASAN_OPTIONS", "UBSAN_OPTIONS", "TSAN_OPTIONS", "LSAN_OPTIONS")}
S14 = [("LmrQuietBase", 93), ("LmrQuietDivisor", 205), ("LmrNoisyBase", 13),
       ("LmrNoisyDivisor", 333), ("LmrHistoryDivisor", 5643), ("NullMoveBase", 5),
       ("LmpBase", 8), ("HistoryPruneMultiplier", 2220), ("HistoryBonusQuadratic", 24),
       ("HistoryBonusLinear", 54), ("HistoryBonusMax", 2212), ("SingularDepth", 6),
       ("IirDepth", 2), ("NonPawnCorrection", "true")]
PC20 = S14 + [("CuckooRep", "true"), ("HistRework", 2), ("TtPruneV2", "true"),
              ("CorrHistV2", "true"), ("MateAlphaGuard", "true"), ("OwnBook", "false")]
FEN = "r1bqk2r/pppp1ppp/2n2n2/2b1p3/2B1P3/2N2N2/PPPP1PPP/R1BQK2R w KQkq - 0 1"
GO = "go wtime 6000 btime 6000 winc 60 binc 60"


def search(settings, go, timeout=300.0):
    p = subprocess.Popen([EXE], stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                         stderr=subprocess.DEVNULL, text=True, bufsize=1, env=ENV)
    out = []
    lock = threading.Lock()

    def pump():
        try:
            for l in p.stdout:
                with lock:
                    out.append(l.rstrip("\n"))
        except Exception:
            pass

    threading.Thread(target=pump, daemon=True).start()

    def send(s):
        p.stdin.write(s + "\n")
        p.stdin.flush()

    def ready(t=180.0):
        with lock:
            k = len(out)
        send("isready")
        t0 = time.monotonic()
        while time.monotonic() - t0 < t:
            with lock:
                if any(x.strip() == "readyok" for x in out[k:]):
                    return
            time.sleep(0.003)

    send("uci")
    time.sleep(0.08)
    send("setoption name Threads value 1")
    ready()
    send("setoption name Hash value 16")
    ready()
    bad = []
    for n, v in settings:
        with lock:
            k = len(out)
        send("setoption name %s value %s" % (n, v))
        ready()
        with lock:
            bad += [x for x in out[k:] if "unknown option" in x or "invalid value" in x]
    send("ucinewgame")
    ready()
    send("position fen " + FEN)
    ready()
    with lock:
        k = len(out)
        refused = [x for x in out[k:] if "invalid FEN" in x]
    assert not refused, "FEN REFUSED: %s" % refused          # 30-F62 gate
    assert not bad, "option refused: %s" % bad
    with lock:
        mark = len(out)
    t0 = time.monotonic()
    send(go)
    while time.monotonic() - t0 < timeout:
        with lock:
            if any(x.startswith("bestmove") for x in out[mark:]):
                break
        time.sleep(0.003)
    el = time.monotonic() - t0
    with lock:
        blk = out[mark:]
    send("quit")
    try:
        p.wait(timeout=20)
    except Exception:
        p.kill()
    bm = score = depth = nodes = None
    for l in blk:
        if l.startswith("bestmove"):
            parts = l.split()
            bm = parts[1] if len(parts) > 1 else None
        if l.startswith("info depth") and " pv" in l:
            t = l.split()
            if "depth" in t:
                depth = int(t[t.index("depth") + 1])
            if "nodes" in t:
                nodes = int(t[t.index("nodes") + 1])
            if "score" in t:
                i = t.index("score")
                score = " ".join(t[i + 1:i + 3])
    return {"bestmove": bm, "score": score, "depth": depth, "nodes": nodes,
            "ms": round(el * 1000, 1)}


def main():
    outdir = sys.argv[1]
    load_n = int(sys.argv[2]) if len(sys.argv) > 2 else 4
    os.makedirs(outdir, exist_ok=True)
    report = {"fen": FEN, "go": GO, "load_procs": load_n, "solo": [], "load": []}
    print("PC r15 + PC20, Threads 1, Hash 16, %s" % GO)
    print("--- 3 SOLO runs ---")
    for i in range(3):
        r = search(PC20, GO)
        report["solo"].append(r)
        print("  solo %d: %s d=%s n=%s %sms" % (i, r["bestmove"], r["depth"], r["nodes"], r["ms"]))
    print("--- 3 LOADED runs (%d busy processes) ---" % load_n)
    hogs = [subprocess.Popen(["bash", "-c", "while :; do :; done"]) for _ in range(load_n)]
    try:
        for i in range(3):
            r = search(PC20, GO)
            report["load"].append(r)
            print("  load %d: %s d=%s n=%s %sms" % (i, r["bestmove"], r["depth"], r["nodes"], r["ms"]))
    finally:
        for h in hogs:
            h.kill()
    def sig(rows):
        return {(r["bestmove"], r["depth"], r["nodes"], r["score"]) for r in rows}
    solo_sig, load_sig = sig(report["solo"]), sig(report["load"])
    report["summary"] = {
        "solo_distinct": len(solo_sig), "load_distinct": len(load_sig),
        "identical_across_conditions": solo_sig == load_sig,
        "solo_ms": [r["ms"] for r in report["solo"]],
        "load_ms": [r["ms"] for r in report["load"]],
    }
    print()
    print(json.dumps(report["summary"], indent=1))
    with open(os.path.join(outdir, "check_s28f43.json"), "w") as f:
        json.dump(report, f, indent=1)


if __name__ == "__main__":
    main()
