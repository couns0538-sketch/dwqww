#!/usr/bin/env python3
"""Q8: whether the `game_ply` "defect" is a defect at all — an honest re-test.

The first write-up claimed `Book Depth` depends on metadata "rather than chess".
Measuring the fix candidates showed something that undercuts that claim, so this
script tests the claim itself rather than the fix.

What the lock actually does (src/uci.cpp:127-129) is not "read the counter":

    game_ply = 2*(fullmove-1) + (black?1:0)

evaluated on the board *after* `position` has applied its moves. Because
`Board::make_move` increments the fullmove counter, that expression equals

    (counter implied by the FEN)  +  (moves appended after the FEN)

i.e. the total ply count, provided the supplied FEN's counter was itself honest.

So there are exactly two cases:

  A. `position startpos moves ...` — counter is generated by the engine, so it
     cannot be wrong. The derivation is exact.
  B. `position fen <FEN> moves ...` — the counter is the caller's statement about
     how many moves preceded the FEN. A FEN contains no history, so the counter is
     the ONLY available record of that. No derivation can recover a true ply that
     was never transmitted.

The second point is the one that decides whether this is a defect. It is tested by
building the only alternative that ignores the counter (`history_size()-1`, which
sees just the moves appended after the FEN) and checking whether it is *closer* to
the truth on case B. If it is not, the counter is not replaceable and the
dependence is an information limit, not a bug.

Scenarios, each with the answer the caller's own input implies:

  A1  `startpos moves ...` at ply 6, Book Depth 7        -> book
  A2  `startpos moves ...` at ply 6, Book Depth 6        -> no book
  B1  `fen <honest> moves ...` effective ply 6, Depth 7  -> book
  B2  `fen <honest> moves ...` effective ply 6, Depth 6  -> no book
  B3  `fen <counter +2 plies> moves ...` effective 8, Depth 7 -> no book
      (the input says ply 8; honouring the input is correct behaviour)
"""

from __future__ import annotations

import sys
from pathlib import Path

import chess

sys.path.insert(0, str(Path(__file__).parent))
from uci import Engine  # noqa: E402

CLOCK = "wtime 10000 btime 10000 winc 100 binc 100"
LINE = "e2e4 c7c5 c2c3 e7e5 g1f3 b8c6"


def probe(binary: str, position: str, depth: int) -> bool:
    eng = Engine(binary)
    try:
        eng.handshake()
        eng.newgame()
        eng.setoption("OwnBook", "true")
        eng.setoption("Book Variety", "0")
        eng.setoption("Book Depth", str(depth))
        eng.position_checked(position)
        reply = eng.go_and_wait(CLOCK, timeout=30.0)
        return any("book move" in ln for ln in reply.lines)
    finally:
        eng.quit()


def main() -> int:
    lock = sys.argv[1] if len(sys.argv) > 1 else "/tmp/build65/forge"
    naive = sys.argv[2] if len(sys.argv) > 2 else "/tmp/sw65-fixes/naive-build/forge"

    moves = LINE.split()
    # Case B base: after two plies, then four appended moves.
    b = chess.Board()
    for _ in range(2):
        b.push(chess.Move.from_uci(moves.pop(0)))
    honest = b.fen()
    tail = " ".join(moves)

    inflated_parts = honest.split()
    inflated_parts[5] = str(int(inflated_parts[5]) + 1)  # +2 plies
    inflated = " ".join(inflated_parts)

    cases = [
        ("A1", f"startpos moves {LINE}", 7, True),
        ("A2", f"startpos moves {LINE}", 6, False),
        ("B1", f"fen {honest} moves {tail}", 7, True),
        ("B2", f"fen {honest} moves {tail}", 6, False),
        ("B3", f"fen {inflated} moves {tail}", 7, False),
    ]

    for _k, pos, _d, _e in cases:
        assert "fen" not in pos or chess.Board(pos.split(" moves")[0][4:]).is_valid()

    print(f"lock  {lock}")
    print(f"naive {naive}")
    print()
    print("| case | position form | input implies ply | Book Depth | expected | LOCK | NAIVE |")
    print("| --- | --- | ---: | ---: | --- | --- | --- |")
    lock_wrong, naive_wrong = 0, 0
    for key, pos, depth, expect in cases:
        form = "startpos" if pos.startswith("startpos") else "fen + moves"
        implies = {"A1": 6, "A2": 6, "B1": 6, "B2": 6, "B3": 8}[key]
        l = probe(lock, pos, depth)
        n = probe(naive, pos, depth)
        lock_wrong += 1 if l != expect else 0
        naive_wrong += 1 if n != expect else 0
        print(f"| {key} | {form} | {implies} | {depth} | {'book' if expect else 'no book'} | "
              f"{'book' if l else 'no book'}{'' if l == expect else ' **WRONG**'} | "
              f"{'book' if n else 'no book'}{'' if n == expect else ' **WRONG**'} |")

    total = len(cases)
    print()
    print(f"LOCK  wrong: {lock_wrong}/{total}")
    print(f"NAIVE wrong: {naive_wrong}/{total}")
    print()
    print("B1/B2 show the lock is exact when the FEN counter is honest. B3 shows it")
    print("honours a counter the caller inflated — which is the only ply information")
    print("the caller supplied, since a FEN carries no history. NAIVE fails A2 and")
    print("B2 because it counts only the moves appended after the FEN and therefore")
    print("under-reports the depth of any resumed game.")
    return 0 if lock_wrong == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
