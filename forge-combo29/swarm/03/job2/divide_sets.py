#!/usr/bin/env python3
"""divide_sets.py EXE FENFILE OUT : perft-1 DIVIDE SET comparison, not just node counts.

For every FEN: engine `go perft 1` gives one line "<move>: <count>" per generated root move; python-chess gives its
legal move list. The two SETS of root moves are compared move by move, so a position where the engine generates a
different move but the same COUNT is caught (a node-sum comparison cannot see that).
Output: a summary block plus one line per disagreement (MISSING = python-chess has it, engine does not;
EXTRA = engine has it, python-chess does not). Raw transcripts under OUT.raw/.
"""
import os, subprocess, sys
import chess

EXE, FENFILE, OUT = sys.argv[1], sys.argv[2], sys.argv[3]
BATCH = int(sys.argv[4]) if len(sys.argv) > 4 else 200
os.makedirs(OUT + ".raw", exist_ok=True)
fens = [l.rstrip("\n").split("\t")[-1] for l in open(FENFILE) if l.strip()]

missing, extra, refused, errs = [], [], [], []
checked = 0
for lo in range(0, len(fens), BATCH):
    hi = min(lo + BATCH, len(fens))
    p = subprocess.Popen([EXE], stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                         stderr=subprocess.STDOUT, text=True, bufsize=1)
    raw = open(f"{OUT}.raw/batch_{lo:05d}_{hi:05d}.txt", "w")

    def send(c):
        raw.write(f">>> {c}\n")
        p.stdin.write(c + "\n"); p.stdin.flush()

    def until(prefix):
        lines = []
        while True:
            line = p.stdout.readline()
            if line == "":
                raise RuntimeError(f"engine died waiting for {prefix}")
            raw.write(line)
            s = line.strip()
            lines.append(s)
            if s.startswith(prefix):
                return lines

    send("uci"); until("uciok")
    send("isready"); until("readyok")
    send("ucinewgame"); send("isready"); until("readyok")
    for i in range(lo, hi):
        fen = fens[i]
        b = chess.Board()
        try:
            b.set_fen(fen)
        except Exception as e:  # noqa: BLE001
            refused.append((i, fen, str(e)))
            continue
        legal = {m.uci() for m in b.legal_moves}
        send(f"position fen {fen}")
        send("isready")
        lines = until("readyok")
        for l in lines:
            if "invalid FEN" in l or "illegal move" in l:
                errs.append((i, l))
        send("go perft 1")
        engine = set()
        while True:
            line = p.stdout.readline()
            if line == "":
                raise RuntimeError(f"engine died at {i}")
            raw.write(line)
            s = line.strip()
            if s.startswith("nodes "):
                break
            if ":" in s and not s.startswith(("info", "option", "id")):
                engine.add(s.split(":")[0].strip())
        checked += 1
        for mv in sorted(legal - engine):
            missing.append((i, mv, fen))
        for mv in sorted(engine - legal):
            extra.append((i, mv, fen))
    send("quit")
    try:
        p.wait(timeout=60)
    except Exception:  # noqa: BLE001
        p.kill()
    raw.close()

with open(OUT + ".diffs", "w") as f:
    for i, mv, fen in missing:
        f.write(f"MISSING\t{i}\t{mv}\t{fen}\n")
    for i, mv, fen in extra:
        f.write(f"EXTRA\t{i}\t{mv}\t{fen}\n")
    for i, fen, why in refused:
        f.write(f"PYREFUSED\t{i}\t{why}\t{fen}\n")
print(f"positions checked: {checked} of {len(fens)}")
print(f"python-chess refused: {len(refused)}")
print(f"moves in python-chess but NOT generated by the engine: {len(missing)}")
print(f"moves generated by the engine but NOT legal in python-chess: {len(extra)}")
print(f"positions with any disagreement: {len({i for i, _, _ in missing} | {i for i, _, _ in extra})}")
print(f"engine error lines: {len(errs)}")
for row in missing[:10]:
    print("MISSING", row)
for row in extra[:10]:
    print("EXTRA", row)
