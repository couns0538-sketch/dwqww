#!/usr/bin/env python3
"""assert_measured.py FILE MODE : fail LOUDLY if a result file does not actually contain the measurements.

Written after seat 19's warning that a parser which finds no number can compare NaN and print "CONFIRMS".
Nothing in my comparison chain ever printed a verdict from a missing number — `compare.py` counts a None as
MISSING and never as equal — but that was an argument, not a check. This is the check.

MODE=perft JSON MAXDEPTH NEXPECT:
  every one of NEXPECT positions must have an integer >= 0 at every depth 1..MAXDEPTH; at least one depth must
  have a strictly positive sum (a file of zeros is a parser failure, not a measurement).
MODE=divide TEXT : the summary must show "positions checked: N of N" with N equal to NEXPECT and the line must be
  present (an empty file or a missing header fails).
"""
import json
import re
import sys

mode = sys.argv[1]
path = sys.argv[2]

if mode == "perft":
    maxdepth, nexpect = int(sys.argv[3]), int(sys.argv[4])
    d = json.load(open(path))
    res = d["results"]
    if len(res) != nexpect:
        sys.exit(f"FAIL {path}: {len(res)} positions in file, expected {nexpect}")
    sums = {k: 0 for k in range(1, maxdepth + 1)}
    for i in range(nexpect):
        row = res.get(str(i))
        if not row:
            sys.exit(f"FAIL {path}: position {i} has no record at all")
        for dep in range(1, maxdepth + 1):
            v = row.get(str(dep))
            if not isinstance(v, int) or isinstance(v, bool):
                sys.exit(f"FAIL {path}: position {i} depth {dep} is {v!r}, not an integer")
            if v < 0:
                sys.exit(f"FAIL {path}: position {i} depth {dep} is negative ({v})")
            sums[dep] += v
    if max(sums.values()) <= 0:
        sys.exit(f"FAIL {path}: every depth sums to 0 — no measurement was parsed")
    print(f"OK {path}: {nexpect} positions x depths 1..{maxdepth} all integer; "
          f"sums {[sums[k] for k in sorted(sums)]}")

elif mode == "divide":
    nexpect = int(sys.argv[3])
    txt = open(path).read()
    m = re.search(r"positions checked: (\d+) of (\d+)", txt)
    if not m:
        sys.exit(f"FAIL {path}: no 'positions checked: N of N' summary line — the harness did not report")
    checked, total = int(m.group(1)), int(m.group(2))
    if checked != nexpect or total != nexpect:
        sys.exit(f"FAIL {path}: checked {checked} of {total}, expected {nexpect}")
    for key in ("moves in python-chess but NOT generated by the engine",
                "moves generated by the engine but NOT legal in python-chess"):
        if key not in txt:
            sys.exit(f"FAIL {path}: missing the '{key}' count — cannot tell measured from unmeasured")
    print(f"OK {path}: {checked} of {total} positions reported, both counts present")

else:
    sys.exit(f"unknown mode {mode}")
