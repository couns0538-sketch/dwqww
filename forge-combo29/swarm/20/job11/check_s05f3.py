#!/usr/bin/env python3
"""check_s05f3.py — seat 20, area 10 job 11: my OWN check of seat 05's S-F3.

Claim: the fifty-move draw shows up in the ROOT score about 9 plies early (cp 0 from halfmove 91 on a K+R v K
board), not at 100.

I build my own boards and sweep the halfmove counter. For every value I record the score, the node count and
whether the pv is empty — because that is what separates "the search saw the draw" from "the root shortcut
declared it".

usage: check_s05f3.py <exe> <outdir>
"""
import json
import os
import re
import subprocess
import sys
import threading
import time

import chess

EXE, OUT = sys.argv[1], sys.argv[2]
os.makedirs(OUT, exist_ok=True)


def search(fen, go="go depth 10", timeout=120.0):
    p = subprocess.Popen([EXE], stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                         stderr=subprocess.STDOUT, text=True, bufsize=1)
    out = []
    lock = threading.Lock()

    def rd():
        try:
            for l in p.stdout:
                with lock:
                    out.append(l.rstrip("\n"))
        except Exception:
            pass
    threading.Thread(target=rd, daemon=True).start()
    for c in ("uci", "setoption name OwnBook value false", "isready", "ucinewgame", "isready",
              f"position fen {fen}", "isready"):
        p.stdin.write(c + "\n")
        p.stdin.flush()
    t0 = time.monotonic()
    p.stdin.write(go + "\n")
    p.stdin.flush()
    while time.monotonic() - t0 < timeout:
        with lock:
            if any(x.startswith("bestmove") for x in out):
                break
        time.sleep(0.003)
    wall = time.monotonic() - t0
    try:
        p.stdin.write("quit\n")
        p.stdin.flush()
        p.wait(timeout=15)
    except Exception:
        p.kill()
    with lock:
        lines = list(out)
    depths = [x for x in lines if x.startswith("info depth")]
    best = [x for x in lines if x.startswith("bestmove")]
    if not depths:
        return {"score": None, "nodes": 0, "pv": [], "bestmove": best[-1].split()[1] if best else None,
                "wall": wall, "empty_pv": True}
    last = depths[-1]
    m = re.search(r"score (\S+)(?: (\S+))?", last)
    score = f"{m.group(1)} {m.group(2)}" if m and m.group(2) else (m.group(1) if m else "?")
    n = re.search(r"nodes (\d+)", last)
    nodes = int(n.group(1)) if n else 0
    pv = []
    if " pv " in last:
        pv = last.split(" pv ", 1)[1].split()
    return {"score": score, "nodes": nodes, "pv": pv,
            "bestmove": best[-1].split()[1] if best else None, "wall": wall,
            "empty_pv": len(pv) == 0}


def with_halfmove(fen, hm):
    parts = fen.split()
    parts[4] = str(hm)
    return " ".join(parts)


BOARDS = [
    ("KR_v_K_a", "1K6/8/8/3R4/8/8/8/k7 w - - 0 1"),
    ("KR_v_K_b", "3k4/8/8/R7/8/8/8/7K w - - 0 1"),     # generated by my own seed, python-chess is_valid True
    ("KR_v_K_c", "4R3/k7/8/8/8/4K3/8/8 w - - 0 1"),
    ("KQ_v_K", "8/5K2/7Q/4k3/8/8/8/8 w - - 0 1"),
    ("mate_in_1", "6k1/5ppp/8/8/8/8/5PPP/3Q2K1 w - - 0 1"),
]
SWEEP = [0, 50, 80, 85, 88, 89, 90, 91, 92, 95, 96, 97, 98, 99, 100]

rows = []
print(f"exe {EXE}")
print(f"{'board':10s} {'halfmove':>8s} {'score':>10s} {'nodes':>9s} {'pv len':>6s} {'bestmove':8s} {'wall ms':>8s}")
for name, fen in BOARDS:
    # guard: refuse to measure an illegal FEN (the engine would keep the PREVIOUS position and I would
    # silently be measuring that instead)
    b0 = chess.Board(with_halfmove(fen, 0))
    assert b0.is_valid(), f"ILLEGAL FEN in my own list: {fen} ({b0.status()})"
    for hm in SWEEP:
        f = with_halfmove(fen, hm)
        r = search(f)
        rows.append({"board": name, "fen": f, "halfmove": hm, **r})
        print(f"{name:10s} {hm:8d} {str(r['score']):>10s} {r['nodes']:9d} {len(r['pv']):6d} "
              f"{str(r['bestmove']):8s} {r['wall']*1000:8.1f}")

print()
print("onset of score == 0 per board (the first halfmove value whose score is a plain cp 0 / mate-free zero):")
for name, _ in BOARDS:
    rr = [r for r in rows if r["board"] == name]
    onset = None
    for r in rr:
        if r["score"] in ("cp 0",) :
            onset = r
            break
    if onset:
        print(f"  {name:10s} first zero at halfmove {onset['halfmove']:3d}  nodes {onset['nodes']:9d}  "
              f"pv len {len(onset['pv'])}  empty_pv {onset['empty_pv']}")
    else:
        print(f"  {name:10s} no zero in the sweep")

with open(os.path.join(OUT, "check_s05f3.json"), "w") as f:
    json.dump(rows, f, indent=1)
print("\nwrote check_s05f3.json")
