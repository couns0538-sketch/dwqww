"""Generate the soak position set R: random legal games, one position every 7 plies.

Deterministic from SEED so the set can be regenerated byte-identically.
"""
import random
import sys

import chess

SEED = 6901          # seat-style seed for this seat's own set
GAMES = 120
EVERY = 7
SKIP_OPENING = 8     # do not take positions in the first 8 plies (all book-ish)

curated = [
    # startpos and the standard test positions, kept because they are the ones
    # other seats quote; the random set is the varied backbone.
    "rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1",
    "r3k2r/p1ppqpb1/bn2pnp1/3PN3/1p2P3/2N2Q1p/PPPBBPPP/R3K2R w KQkq - 0 1",
    "8/2p5/3p4/KP5r/1R3p1k/8/4P1P1/8 w - - 0 1",
    "r3k2r/Pppp1ppp/1b3nbN/nP6/BBP1P3/q4N2/Pp1P2PP/R2Q1RK1 w kq - 0 1",
    "rnbq1k1r/pp1Pbppp/2p5/8/2B5/8/PPP1NnPP/RNBQK2R w KQ - 1 8",
    "r4rk1/1pp1qppp/p1np1n2/2b1p1B1/2B1P1b1/P1NP1N2/1PP1QPPP/R4RK1 w - - 0 10",
    "8/8/8/4k3/8/8/4K3/8 w - - 0 1",
    "8/8/8/8/8/5k2/6q1/7K w - - 0 1",
    "4k3/8/8/8/8/8/4P3/4K3 w - - 0 1",
    "8/8/8/8/8/8/6k1/4K2R w K - 0 1",
]


def main(path):
    rng = random.Random(SEED)
    out = list(curated)
    seen = set(out)
    made = 0
    while made < GAMES:
        board = chess.Board()
        ply = 0
        while not board.is_game_over(claim_draw=False) and ply < 200:
            moves = list(board.legal_moves)
            if not moves:
                break
            board.push(rng.choice(moves))
            ply += 1
            if ply >= SKIP_OPENING and ply % EVERY == 0:
                fen = board.fen()
                if fen not in seen:
                    seen.add(fen)
                    out.append(fen)
        made += 1
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("positions", len(out))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "positions_R.fens")
