#!/usr/bin/env bash
# make_honesty_txt.sh : builds HONESTY.txt from the raw files in honesty/ (no number typed by hand).
set -u
S=$(cat ~/swarm_seat.txt)
D="forge-combo29/swarm/$S"
OUT="$D/HONESTY.txt"
{
  echo "# HONESTY CHECK - seat $S - build of 6b98f217 (worktree $(grep -m1 exe_started "$D/honesty/bench11.meta" | cut -d' ' -f2-))"
  echo "# generated by $D/make_honesty_txt.sh at $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  grep -h . "$D/honesty/bench11.meta" | sed 's/^/# /'
  echo "# build: cmake Release, g++ $(g++ -dumpfullversion), default -march=x86-64-v4, FORGE_PORTABLE off"
  echo "# raw outputs in $D/honesty/"
  echo
  echo "| check | required | got | pass |"
  echo "|---|---|---|---|"
  for d in 11 13 16; do
    got=$(grep -o 'nodes [0-9]*' "$D/honesty/bench$d.raw.txt" | head -1 | awk '{print $2}')
    case $d in 11) req=312866;; 13) req=862329;; 16) req=3024920;; esac
    [ "$got" = "$req" ] && r=PASS || r=FAIL
    echo "| bench $d | $req | $got | $r |"
  done
  got=$(grep -oE '^nodes [0-9]+' "$D/honesty/perft5.raw.txt" | awk '{print $2}')
  [ "$got" = "4865609" ] && r=PASS || r=FAIL
  echo "| go perft 5 | 4865609 | $got | $r |"
  echo
  if grep -q '| FAIL |' "$OUT" 2>/dev/null; then echo "A BUILD THAT MISSES ONE IS NOT USED."; else echo "ALL FOUR MATCH - this build is used for every job."; fi
} > "$OUT"
cat "$OUT"
