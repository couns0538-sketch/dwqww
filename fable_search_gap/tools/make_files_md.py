"""Write fable_search_gap/FILES.md: every file this branch adds or changes relative to origin/main,
with md5 and sha256 of the working-tree bytes, followed by the hand-written handoff text.

Run it last, after every other file is final: any later edit changes a hash.
FILES.md cannot list its own hash; that is stated in the file.

usage: make_files_md.py REPO
"""
import hashlib
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pinguard  # noqa: E402


def digest(path: str, algo: str) -> str:
    h = hashlib.new(algo)
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    repo = sys.argv[1]
    pinguard.ensure()
    run = lambda *a: subprocess.run(["git", "-C", repo, "-c", "core.quotepath=false", *a], check=True,
                                    capture_output=True, text=True, encoding="utf-8").stdout
    tracked = run("diff", "--name-status", "origin/main", "HEAD").strip().split("\n")
    pending = run("status", "--porcelain").strip().split("\n")
    names = {}
    for line in tracked:
        if line.strip():
            status, path = line.split("\t", 1)
            names[path] = "added" if status.startswith("A") else "changed"
    for line in pending:
        if line.strip():
            path = line[3:].strip().strip('"')
            if os.path.isdir(os.path.join(repo, path)):
                for root, _d, files in os.walk(os.path.join(repo, path)):
                    for f in files:
                        names.setdefault(os.path.relpath(os.path.join(root, f), repo).replace("\\", "/"), "added")
            else:
                names.setdefault(path, "added")
    out_path = os.path.join(repo, "fable_search_gap", "FILES.md")
    names.pop("fable_search_gap/FILES.md", None)
    head = run("rev-parse", "HEAD").strip()
    base = run("rev-parse", "origin/main").strip()
    lines = ["# FILES: everything this branch adds", "",
             f"Branch `fable52-search-gap-20261109`, base `origin/main` `{base}`. Generated by `tools/make_files_md.py` "
             f"on top of commit `{head[:8]}`; the commit that adds this file is one later.",
             "",
             "Hashes are of the file bytes as committed (line endings are not converted in this clone). "
             "`FILES.md` itself is not listed because a file cannot contain its own hash. "
             "No file that existed on `main` was changed, and no engine source file was added.",
             "",
             f"Files: {len(names)}.", "",
             "| File | Status | Bytes | md5 | sha256 |", "|---|---|---|---|---|"]
    for path in sorted(names):
        full = os.path.join(repo, path)
        if not os.path.isfile(full):
            continue
        lines.append(f"| `{path}` | {names[path]} | {os.path.getsize(full)} | `{digest(full, 'md5')}` | `{digest(full, 'sha256')}` |")
    tail = os.path.join(os.path.dirname(os.path.abspath(__file__)), "files_md_tail.md")
    if os.path.isfile(tail):
        with open(tail, encoding="utf-8") as f:
            lines += ["", f.read().rstrip("\n")]
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out_path}: {len(names)} files")


if __name__ == "__main__":
    main()
