#!/usr/bin/env python3
"""make_index.py - Opus R15: build INDEX.md (gate-ready lines for the crew) from every <root>/<name>/RESULT.json.

usage: python -I -B make_index.py [--root D:\\o15\\cands] [--copy-to DIR] [--ci-dir DIR]

Each RESULT.json is written by cand_pack.ps1 (kind "candidate", the default) or by hand for an existing exe that was
never gated alone (kind "extra"). An optional <root>/<name>/ci.json ({"run": id, "conclusion": "success", "commit": sha})
fills the CI column. The table is regenerated as a whole every time (never edited in place); rows are sorted by name.
Exit 0 = written; 1 = a RESULT.json could not be read (named on stderr, the index is still written without it).
"""
import argparse
import datetime
import glob
import json
import os
import shutil
import sys

LOCK_EXE = r'C:\Users\Administrator\grok-pc\forge_push\bin\forge_ltopgo_x_al1s198_v23.exe'
LOCK_SHA = 'fd3a51903e73dc1fa20263f1dcc7a4eec506592e9f25e50b8f8739ca36873072'
PINS = {'d11': 312866, 'd13': 862329, 'd16': 3024920, 'd20': 12389307, 'd22': 34048354}


def ok(res, key):
    c = res.get('checks', {}).get(key)
    if c is None:
        return '-'
    return 'PASS' if c.get('ok') else 'FAIL'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--root', default=r'D:\o15\cands')
    ap.add_argument('--copy-to', default='')
    a = ap.parse_args()
    rows, bad = [], 0
    for path in sorted(glob.glob(os.path.join(a.root, '*', 'RESULT.json'))):
        try:
            with open(path, encoding='utf-8-sig') as f:
                res = json.load(f)
        except (OSError, ValueError) as e:
            print(f'make_index: cannot read {path}: {e}', file=sys.stderr)
            bad += 1
            continue
        ci_path = os.path.join(os.path.dirname(path), 'ci.json')
        if os.path.exists(ci_path):
            with open(ci_path, encoding='utf-8-sig') as f:
                res['ci'] = json.load(f)
        res['_path'] = path
        rows.append(res)
    now = datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    out = [
        '# R15 candidate INDEX - gate-ready lines (UNPROVEN until the crew gates them; no Elo claim)',
        '',
        f'Generated by `opus_r15/tools/make_index.py` from `{a.root}\\*\\RESULT.json` at {now} (PC clock).',
        f'Engine B for every line: the lock `{LOCK_EXE}` (sha256 `{LOCK_SHA}`), no setoption.',
        'Engine A: the exe of the row + its setoption line (one option per line; every option is advertised with',
        'default 0, as the gate runner requires). Gate PC precondition before game 1: engine A without the setoption',
        'benches the lock pins d11 312866 / d13 862329 / d16 3024920 / d20 12389307 / d22 34048354, and with it the ON',
        'numbers of its row. The crew gates with [0, 5]; nothing here is queued.',
        '',
        '| # | line | exe (full path) | sha256 | setoption (ON) | ON bench d11 / d13 / d16 | OFF = pins | pc1 = pc2 | smoke 2 min | CI | verdict |',
        '|---|---|---|---|---|---|---|---|---|---|---|',
    ]
    cands = [r for r in rows if r.get('kind', 'candidate') == 'candidate' and r.get('option')]
    extras = [r for r in rows if r.get('kind') == 'extra']
    base = [r for r in rows if r.get('kind', 'candidate') == 'candidate' and not r.get('option')]
    for i, r in enumerate(cands, 1):
        on = r.get('pin_on') or {}
        sm = r.get('smoke') or {}
        smoke = (f"{sm.get('verdict', '-')} ({sm.get('games', '?')} games, {sm.get('illegal', '?')} illegal, "
                 f"{sm.get('crashes', '?')} crashes)") if sm else '-'
        ci = r.get('ci') or {}
        ci_txt = f"{ci.get('conclusion', '?')} {ci.get('run', '')}".strip() if ci else 'pending'
        out.append(f"| {i} | {r['name']} | `{r.get('exe', '')}` | `{r.get('exe_sha256', '')}` | "
                   f"`setoption name {r['option']} value {r['on']}` | {on.get('d11', '?')} / {on.get('d13', '?')} / "
                   f"{on.get('d16', '?')} | {ok(r, 'pin_off')} | {ok(r, 'pc1_equals_pc2')} | {smoke} | {ci_txt} | "
                   f"{r.get('verdict', '?')} |")
    if not cands:
        out.append('| - | (none yet) | | | | | | | | | |')
    out += ['', '## Per line', '']
    for r in cands:
        on = r.get('pin_on') or {}
        out += [f"### {r['name']} - `{r['option']}` = {r['on']}", '']
        if r.get('idea'):
            out.append(f"- idea: {r['idea']}")
        out += [
            f"- exe: `{r.get('exe', '')}` sha256 `{r.get('exe_sha256', '')}` md5 `{r.get('exe_md5', '')}` "
            f"(kit v2.3 -Expose, tag {r.get('tag', '')}, pc1 = pc2: {ok(r, 'pc1_equals_pc2')})",
            f"- patch: `{r.get('patch', '')}` sha256 `{r.get('patch_sha256', '')}` (applies with `patch -p1` to git "
            f"{r.get('lock_source', '')[:12]})",
            f"- ON bench: d11 {on.get('d11', '?')}, d13 {on.get('d13', '?')}, d16 {on.get('d16', '?')}, "
            f"d20 {on.get('d20', '?')}, d22 {on.get('d22', '?')}; perft startpos 4865609 / kiwipete 193690690",
            '- checks: ' + ', '.join(f"{k} {'PASS' if v.get('ok') else 'FAIL'}" for k, v in r.get('checks', {}).items()),
            f"- record: `{r['_path']}`",
            '- fastchess engine A (the form of the crew\'s running gates; engine B = the lock with the same three options):',
            f"  `-engine name=cand_r15_{r['name']} cmd={r.get('exe', '')} option.Threads=2 option.Hash=16 "
            f"option.OwnBook=false option.{r['option']}={r['on']}`",
            '',
        ]
    for r in extras:
        out += [f"- extra {r['name']}: `-engine name=cand_r15_{r['name']} cmd={r.get('exe', '')} option.Threads=2 "
                f"option.Hash=16 option.OwnBook=false option.{r['option']}={r['on']}` (exe copied from "
                f"`{r.get('source_exe', '')}`)"]
    if extras:
        out.append('')
    if extras:
        out += ['## Existing exes, options never gated alone (not R15 patches; listed for the crew, not counted)', '',
                '| line | exe (full path) | sha256 | setoption (ON) | ON bench d11 / d13 / d16 | OFF = pins | smoke | note |',
                '|---|---|---|---|---|---|---|---|']
        for r in extras:
            on = r.get('pin_on') or {}
            sm = r.get('smoke') or {}
            out.append(f"| {r['name']} | `{r.get('exe', '')}` | `{r.get('exe_sha256', '')}` | "
                       f"`setoption name {r['option']} value {r['on']}` | {on.get('d11', '?')} / {on.get('d13', '?')} / "
                       f"{on.get('d16', '?')} | {ok(r, 'pin_off')} | {sm.get('verdict', '-')} | {r.get('note', '')} |")
        out.append('')
    if base:
        out += ['## Base re-verify (cand_pack -NoPatch self-test)', '']
        for r in base:
            out.append(f"- {r['name']}: exe sha256 `{r.get('exe_sha256', '')}` (lock `{LOCK_SHA}`): "
                       f"{ok(r, 'nopatch_is_lock')}, OFF pins {ok(r, 'pin_off')}, verdict {r.get('verdict', '?')}")
        out.append('')
    text = '\n'.join(out) + '\n'
    target = os.path.join(a.root, 'INDEX.md')
    with open(target, 'w', newline='\n', encoding='utf-8') as f:
        f.write(text)
    print(f'make_index: {target} ({len(cands)} lines, {len(extras)} extras, {len(base)} base runs, {bad} unreadable)')
    if a.copy_to:
        os.makedirs(a.copy_to, exist_ok=True)
        shutil.copyfile(target, os.path.join(a.copy_to, 'INDEX.md'))
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
